"""Copies the RF look's tables from retro-spectrum into the emulator.

    python scripts/rf_tables_inc.py [path to retro-spectrum]

The RF filter (cpp-core/src/rf_filter.cpp, docs/rf-look.md) is specified in
retro-spectrum's docs/spec/rf.md and is meant to give the same pixels as the
FPGA's, bit for bit. So the emulator takes that repository's tables rather
than working them out again: fpga/rtl/video/rf_enc.hex (the encoder, 8,192
entries, 12-bit two's complement) and rf_sc.hex (the demodulator's sine and
cosine, 256 entries of {S, C} as signed bytes). This writes them as
cpp-core/src/generated/rf_tables.inc. The default path is the sibling checkout,
../retro-spectrum.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "cpp-core" / "src" / "generated" / "rf_tables.inc"


def signed(value, bits):
    return value - (1 << bits) if value & (1 << (bits - 1)) else value


def rows(values, per_row):
    out = []
    for i in range(0, len(values), per_row):
        out.append("    " + ", ".join(str(v) for v in values[i:i + per_row]) + ",")
    return out


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "retro-spectrum"
    video = source / "fpga" / "rtl" / "video"
    enc = [signed(int(line, 16), 12) for line in (video / "rf_enc.hex").read_text().split()]
    sc = [int(line, 16) for line in (video / "rf_sc.hex").read_text().split()]
    if len(enc) != 8192 or len(sc) != 256:
        print("unexpected table sizes:", len(enc), len(sc))
        return 1
    lines = [
        "// Generated by scripts/rf_tables_inc.py from retro-spectrum's",
        "// fpga/rtl/video/rf_enc.hex and rf_sc.hex -- do not edit. See rf_filter.h.",
        "",
        "// ENC[sw is -1][colour][phase], the composite level of a sample.",
        "const int16_t RF_ENC[8192] = {",
        *rows(enc, 16),
        "};",
        "",
        "// S[phase] = round(127 sin), the U demodulator.",
        "const int8_t RF_SIN[256] = {",
        *rows([signed(v >> 8, 8) for v in sc], 16),
        "};",
        "",
        "// C[phase] = round(127 cos), the V demodulator.",
        "const int8_t RF_COS[256] = {",
        *rows([signed(v & 0xFF, 8) for v in sc], 16),
        "};",
        "",
    ]
    OUT.write_text("\n".join(lines), newline="\n")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
