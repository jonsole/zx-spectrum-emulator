DESC_PATH = PROJECT_ROOT / "vendor" / "chips" / "z80_desc.yml"
OUT_PATH = PROJECT_ROOT / "cpp-core" / "src" / "generated" / "dispatch.inc"

ED_STEP_BASE = 256
EXTRA_STEP_BASE = 512

