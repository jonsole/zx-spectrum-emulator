# ab / db / dst simple-token substitution (mirrors z80_gen.py's map_cpu, but
# only the small set of tokens actually used unprefixed/ED in this file --
# and unlike map_cpu, increment/decrement forms need dedicated Cpu helper
# methods since Rust has no lvalue-expression `x++`).
# ============================================================================

def addr_expr(tok: str, y: int, z: int, p: int, q: int) -> str:
    table = {
        "$ADDR": "addr_",
        "$PC++": "pc_post_inc()",
        "$BC": "regs.bc()",
        "$DE": "regs.de()",
        "$SP": "regs.sp",
        "$SP++": "sp_post_inc()",
        "$SP+1": "uint16_t(regs.sp + 1)",
        "--$SP": "sp_pre_dec()",
        "$WZ": "regs.wz",
        "$WZ++": "wz_post_inc()",
        "cpu->hl": "regs.hl()",
        "cpu->hl++": "hl_post_inc()",
        "cpu->hl--": "hl_post_dec()",
        "cpu->de++": "de_post_inc()",
        "cpu->de--": "de_post_dec()",
    }
    if tok in table:
        return table[tok]
    raise ValueError(f"unhandled address expression: {tok!r}")


def data_read_expr(tok: str, y: int, z: int, p: int, q: int) -> str:
    if tok == "$DLATCH":
        return "dlatch_"
    # $H/$L (bare, unlike $RRY/$RRZ) ARE substitutable in the YAML -- used
    # only by "LD (nn),HL"/"LD HL,(nn)"/"EX (SP),HL" (all p==2-fixed,
    # unprefixed), and real DD/FD-prefixed forms of those (LD (nn),IX,
    # EX (SP),IX, ...) really do read/write IXH/IXL. Verified directly
    # against z80.h (case 607/610 use cpu->hlx[cpu->hlx_idx].l/.h).
    if tok == "$H":
        return "hlx_h()"
    if tok == "$L":
        return "hlx_l()"
    plain_regs = {"$A": "a", "$B": "b", "$C": "c", "$D": "d", "$E": "e"}
    if tok in plain_regs:
        return f"regs.{plain_regs[tok]}"
    if tok == "$RRZ":
        return R[z]
    if tok == "$RRY":
        return R[y]
    if tok == "$PCH":
        return "uint8_t(regs.pc >> 8)"
    if tok == "$PCL":
        return "uint8_t(regs.pc)"
    if tok == "$RP2H":
        return "hlx_h()" if p == 2 else RP2_HIGH[p]
    if tok == "$RP2L":
        return "hlx_l()" if p == 2 else RP2_LOW[p]
    if tok == "$RRPH":
        return RP_HIGH[p]
    if tok == "$RRPL":
        return RP_LOW[p]
    if tok == '"0"' or tok == 0:
        return "0"
    raise ValueError(f"unhandled data-read expression: {tok!r}")


def dest_write_expr(tok: str, y: int, z: int, p: int, q: int) -> str:
    """Returns either a C++ lvalue expression (assignable with `= value;`)
    or one of the `__XXX__` sentinels `emit_dest_assign` special-cases (for
    targets that need a setter *call*, not a plain field), for an `mread`'s
    `dst` field. `$RY == 6` ((HL)) never occurs among the ops this
    generator handles (they route through $DLATCH instead)."""
    if tok == "$DLATCH":
        return "dlatch_"
    if tok == "$RY":
        # Substitutable (LD $RY,n, e.g. -- DD-prefixed LD H,n really means
        # LD IXH,n).
        if y == 4:
            return "__HLXH__"
        if y == 5:
            return "__HLXL__"
        return R[y]
    if tok == "$RRY":
        return R[y]  # never substituted -- see z80_desc.yml's own note
    if tok == "$H":
        return "__HLXH__"
    if tok == "$L":
        return "__HLXL__"
    plain_regs = {"$A": "a", "$B": "b", "$C": "c", "$D": "d", "$E": "e"}
    if tok in plain_regs:
        return f"regs.{plain_regs[tok]}"
    if tok == "$WZL":
        return "__WZL__"  # handled specially, see emit_mread
    if tok == "$WZH":
        return "__WZH__"
    if tok == "$RPL":
        # Substitutable (LD $RP,nn -- DD-prefixed LD HL,nn really means
        # LD IX,nn).
        if p == 2:
            return "__HLXL__"
        return RP_LOW[p] if p != 3 else "__SPL__"
    if tok == "$RPH":
        if p == 2:
            return "__HLXH__"
        return RP_HIGH[p] if p != 3 else "__SPH__"
    if tok == "$RP2L":
        # Substitutable (POP $RP2 -- DD-prefixed POP HL really means POP IX).
        if p == 2:
            return "__HLXL__"
        return RP2_LOW[p]
    if tok == "$RP2H":
        if p == 2:
            return "__HLXH__"
        return RP2_HIGH[p]
    if tok == "$RRPL":
        return RP_LOW[p] if p != 3 else "__SPL__"
    if tok == "$RRPH":
        return RP_HIGH[p] if p != 3 else "__SPH__"
    raise ValueError(f"unhandled dest-write token: {tok!r}")


def emit_dest_assign(tok: str, y: int, z: int, p: int, q: int) -> str:
    target = dest_write_expr(tok, y, z, p, q)
    if target == "__WZL__":
        return "regs.set_wzl(get_data(pins));"
    if target == "__WZH__":
        return "regs.set_wzh(get_data(pins));"
    if target == "__SPL__":
        return "regs.set_spl(get_data(pins));"
    if target == "__SPH__":
        return "regs.set_sph(get_data(pins));"
    if target == "__HLXH__":
        return "set_hlx_h(get_data(pins));"
    if target == "__HLXL__":
        return "set_hlx_l(get_data(pins));"
    return f"{target} = get_data(pins);"


# ============================================================================
# Step/code generation, mirroring z80_gen.py's gen_decoder(): each mcycle
# type expands into a fixed sequence of T-states. Unlike the first draft of
# this generator, step NUMBERS for an entire op are assigned in one flat
# pass over every T-state up front (dispatch_index for the first, then
# Generator.alloc() for every other one, including the trailing
# `overlapped` T-state) -- this is the fix for a real bug caught before
# ever running it: allocating the "next step after this mcycle" lazily,
# without reserving it via alloc(), let a later op's alloc() call hand out
# the SAME number again, silently colliding two different opcodes' code
# onto one match arm.
# ============================================================================

class TState:
    """One HALF-T-state (one generated switch case) within a single
    instruction. `kind` selects which template `render()` uses; `number` is
    assigned by Generator.gen_op(), not at construction time.

    `tindex` is the ordinal of the whole T-state this half belongs to, within
    the op. It exists only so a repeating block instruction's "skip the
    rewind mcycle" jump can be resolved structurally (see gen_op) rather than
    by a hardcoded step offset, which no longer survives the half-T split."""

    def __init__(self, kind: str, tindex: int, **kw):
        self.kind = kind
        self.tindex = tindex
        self.kw = kw
        self.number: int | None = None


def build_tstates(op: Op) -> list[TState]:
    """Flattens one op's `mcycles` into its exact per-HALF-T-state sequence.
    An `overlapped` mcycle is auto-appended if the op doesn't already end
    with one, mirroring parse_opdescs()'s own `num_overlapped == 0` check.

    Every T-state becomes two half-states, H then L, following real Z80 bus
    timing: the address bus goes valid on H, control lines assert on L, and
    WAIT is sampled on L. See z80.h's header comment for why that split is
    the entire point of this rewrite -- it is what makes the "address valid,
    MREQ not yet asserted" window the ULA contends on actually exist.

    The one exception is `overlapped`, which is a single half-state: it IS
    T1H of the next instruction's M1 fetch (that is what the overlapped
    fetch means), and T1L of that fetch is hand-written as STEP_M1_T1L."""
    mcycles = list(op.mcycles)
    if not any(mc["type"] == "overlapped" for mc in mcycles):
        mcycles = mcycles + [{"type": "overlapped"}]

    tstates: list[TState] = []
    # Counts whole T-states as they're emitted, so each half can record which
    # T-state it belongs to.
    t_ord = 0

    def emit(kind: str, **kw) -> None:
        tstates.append(TState(kind, t_ord, **kw))

    def emit_idle_tstate() -> None:
        nonlocal t_ord
        emit("idle")
        emit("idle")
        t_ord += 1

    for mci, mc in enumerate(mcycles):
        t = mc["type"]
        if t == "mread":
            # T1H places the real target address on the bus with NO control
            # bits -- this is the contention window. It is also the ONE place
            # "ab" is evaluated: several "ab" tokens ($PC++, cpu->hl++, ...)
            # are side-effecting post-increments, so every later half-state
            # reuses get_addr(pins) instead of re-running the expression.
            tcycles = mc.get("tcycles", MEM_TCYCLES)
            emit("mread_t1h", ab=mc["ab"])
            emit("mread_t1l")
            t_ord += 1
            emit("idle")
            emit("mread_t2l_wait")
            t_ord += 1
            emit("idle")
            emit("mread_t3l_latch", dst=mc["dst"], mci=mci)
            t_ord += 1
            for _ in range(3, tcycles):
                emit_idle_tstate()
        elif t == "mwrite":
            # Same T1H address-first reasoning as mread. MREQ asserts at T1L,
            # the data goes on the bus at T2H, and WR only asserts at T2L --
            # matching the real chip, where WR deliberately trails MREQ so the
            # data bus has settled before the write strobe.
            tcycles = mc.get("tcycles", MEM_TCYCLES)
            emit("mwrite_t1h", ab=mc["ab"])
            emit("mwrite_t1l")
            t_ord += 1
            emit("mwrite_t2h_data", db=mc["db"])
            emit("mwrite_t2l_wait", mci=mci)
            t_ord += 1
            emit("idle")
            emit("mwrite_t3l_end")
            t_ord += 1
            for _ in range(3, tcycles):
                emit_idle_tstate()
        elif t == "ioread":
            # An I/O cycle is 4 T-states because the Z80 always inserts one
            # wait state (TW) between T2 and T3. IORQ asserts at T2H (not T1L
            # like MREQ) -- the extra half-cycle of address setup is a real
            # difference between the memory and I/O cycles on this chip.
            tcycles = mc.get("tcycles", IO_TCYCLES)
            emit("ioread_t1h", ab=mc["ab"])
            emit("idle")
            t_ord += 1
            emit("ioread_t2h_assert")
            emit("idle")
            t_ord += 1
            emit("idle")
            emit("ioread_tw_l_wait")
            t_ord += 1
            emit("idle")
            emit("ioread_t3l_latch", dst=mc["dst"], mci=mci)
            t_ord += 1
            for _ in range(4, tcycles):
                emit_idle_tstate()
        elif t == "iowrite":
            tcycles = mc.get("tcycles", IO_TCYCLES)
            emit("iowrite_t1h", ab=mc["ab"])
            emit("idle")
            t_ord += 1
            emit("iowrite_t2h_assert", db=mc["db"])
            emit("idle")
            t_ord += 1
            emit("idle")
            emit("iowrite_tw_l_wait")
            t_ord += 1
            emit("idle")
            emit("iowrite_t3l_end", mci=mci)
            t_ord += 1
            for _ in range(4, tcycles):
                emit_idle_tstate()
        elif t == "generic":
            # An internal cycle: no bus activity at all. The action fires on
            # the L half, not the H half, so that EVERY action site in this
            # generator sits on an L half (mread latch, mwrite write, io
            # latch/end are all L too).
            #
            # That uniformity is load-bearing, not cosmetic. A forward branch
            # taken by an action jumps to the target T-state's H half; if the
            # action itself sat on an H half, the jump would skip its own
            # T-state's L half and the instruction would come out half a
            # T-state short. Caught by the differential test's timing check
            # on LDIR's non-repeating exit (15.5 T against the reference's
            # 16), which is exactly the kind of thing register comparison
            # alone would never have noticed.
            emit("idle")
            emit("generic", mci=mci)
            t_ord += 1
            for _ in range(1, mc["tcycles"]):
                emit_idle_tstate()
        elif t == "overlapped":
            # One half-state only -- see this function's own doc comment.
            emit("overlapped", mci=mci, prefix=mc.get("prefix"))
            t_ord += 1
        else:
            raise ValueError(f"{op.name}: unhandled mcycle type {t!r}")
    if tstates[-1].kind != "overlapped":
        raise ValueError(f"{op.name}: internal error, didn't end on 'overlapped'")
    return tstates


class Generator:
    def __init__(self):
        self.cur_extra_step = EXTRA_STEP_BASE
        self.arms: list[str] = []

    def alloc(self) -> int:
        s = self.cur_extra_step
        self.cur_extra_step += 1
        return s

    def gen_op(self, dispatch_index: int | None, op: Op, y: int, z: int, p: int, q: int) -> int:
        """Returns the step number assigned to this op's first half-T-state --
        `dispatch_index` when given explicitly (the main 0..512 opcode
        table), otherwise a freshly `alloc()`'d one (used for standalone
        entries like `cb`/`cbhl` that aren't part of that table but still
        need a real, collision-free step number for hand-written code
        elsewhere to jump to)."""
        tstates = build_tstates(op)
        tstates[0].number = dispatch_index if dispatch_index is not None else self.alloc()
        for ts in tstates[1:]:
            ts.number = self.alloc()

        for i, ts in enumerate(tstates):
            # $NEXTSTEP == this half-state's own natural successor (its
            # `_goto()` target if nothing branches early) -- well-defined
            # for every kind except the last (always 'overlapped', which
            # dispatches via begin_fetch()/begin_fetch_ed() instead of a
            # plain `step_ = next`).
            nxt = tstates[i + 1].number if i + 1 < len(tstates) else None
            # A callable, not a number: the forward-branch distance differs
            # per instruction (5 for the block/relative-jump forms, 6 for
            # RET cc, 7 for CALL cc, 3 for the CB (HL) form), and the action
            # is what knows which applies.
            skip = (lambda idx: lambda k: self.skip_target(tstates, idx, k))(i)
            body = self.render(ts, nxt, skip, op, y, z, p, q)
            self.arms.append(f"        case {ts.number}: {{\n{body}\n        }}")

        return tstates[0].number

    @staticmethod
    def skip_target(tstates: list[TState], i: int, k: int) -> int:
        """Where a forward-branching instruction jumps when it takes the
        "don't do the rest of this" path -- a conditional RET/CALL/JR that
        wasn't taken, or a repeating block instruction that has finished and
        must skip its PC-rewind mcycle.

        The whole-T-state generator wrote this as a raw step offset,
        `nextstep + k`, which worked only because step numbers were assigned
        one per T-state in order. That stopped being true once each T-state
        became two half-states (with `overlapped` the lone one-half
        exception), so the same arithmetic would now land mid-mcycle.

        Resolved structurally instead: `k` still means what it always meant,
        "k T-states past this action's own next T-state", and this looks up
        the half-state that actually starts there. A layout change that
        breaks the assumption raises here rather than silently generating a
        jump into the middle of the wrong machine cycle."""
        target_tindex = tstates[i].tindex + 1 + k
        for ts in tstates:
            if ts.tindex == target_tindex:
                return ts.number
        raise ValueError(
            f"skip target T-state {target_tindex} (this T-state + 1 + {k}) does not "
            f"exist -- the op has only {tstates[-1].tindex + 1} T-states"
        )

    def render(self, ts: TState, nxt: int | None, skip: int | None,
               op: Op, y: int, z: int, p: int, q: int) -> str:
        """Emits the C++ body of one half-T-state's switch case.

        Every case ends by setting `step_` and returning true, except the
        WAIT-check halves (which return WITHOUT advancing `step_`, so the
        same half re-runs until WAIT clears) and `overlapped` (where
        begin_fetch* sets `step_` itself)."""
        goto = f"            step_ = {nxt};\n            return true;"

        if ts.kind == "idle":
            return goto

        # ---- memory read -------------------------------------------------
        if ts.kind == "mread_t1h":
            # The contention window: address valid, no control lines yet.
            # Also the ONE place "ab" is evaluated, so a side-effecting token
            # ($PC++, cpu->hl++) fires exactly once -- every later half reuses
            # get_addr(pins) rather than re-running the expression.
            addr = addr_expr(ts.kw["ab"], y, z, p, q)
            return f"            pins = set_addr(pins, {addr});\n{goto}"
        if ts.kind == "mread_t1l":
            return f"            pins = set_addr_assert(pins, get_addr(pins), MREQ | RD);\n{goto}"
        if ts.kind == "mread_t2l_wait":
            return f"            if (asserted(pins, WAIT)) {{ return true; }}\n{goto}"
        if ts.kind == "mread_t3l_latch":
            dest = emit_dest_assign(ts.kw["dst"], y, z, p, q)
            action = get_action(op.name, ts.kw["mci"], y, z, p, q, skip)
            body = f"            {dest}\n"
            if action:
                body += f"            {action}\n"
            body += "            pins = release_pins(pins, MREQ | RD);\n"
            return body + goto

        # ---- memory write --------------------------------------------------
        if ts.kind == "mwrite_t1h":
            addr = addr_expr(ts.kw["ab"], y, z, p, q)
            return f"            pins = set_addr(pins, {addr});\n{goto}"
        if ts.kind == "mwrite_t1l":
            return f"            pins = set_addr_assert(pins, get_addr(pins), MREQ);\n{goto}"
        if ts.kind == "mwrite_t2h_data":
            # Data is evaluated here, its first and only evaluation (T1H
            # placed the address only). Confirmed that no "db" token used by
            # any real mwrite entry is side-effecting.
            db_tok = ts.kw["db"]
            data = "0" if db_tok in ("0", 0) else data_read_expr(db_tok, y, z, p, q)
            return f"            pins = set_data(pins, {data});\n{goto}"
        if ts.kind == "mwrite_t2l_wait":
            # WR trails MREQ by a half-cycle, as on the real chip: the data
            # bus has to settle before the write strobe.
            action = get_action(op.name, ts.kw["mci"], y, z, p, q, skip)
            body = "            if (asserted(pins, WAIT)) { return true; }\n"
            body += "            pins = assert_pins(pins, WR);\n"
            if action:
                body += f"            {action}\n"
            return body + goto
        if ts.kind == "mwrite_t3l_end":
            return f"            pins = release_pins(pins, MREQ | WR);\n{goto}"

        # ---- I/O read ------------------------------------------------------
        if ts.kind == "ioread_t1h":
            addr = addr_expr(ts.kw["ab"], y, z, p, q)
            return f"            pins = set_addr(pins, {addr});\n{goto}"
        if ts.kind == "ioread_t2h_assert":
            # IORQ asserts a half-cycle later than MREQ would -- a real
            # difference between this chip's memory and I/O cycles, not a
            # transcription slip.
            return f"            pins = set_addr_assert(pins, get_addr(pins), IORQ | RD);\n{goto}"
        if ts.kind == "ioread_tw_l_wait":
            return f"            if (asserted(pins, WAIT)) {{ return true; }}\n{goto}"
        if ts.kind == "ioread_t3l_latch":
            dest = emit_dest_assign(ts.kw["dst"], y, z, p, q)
            action = get_action(op.name, ts.kw["mci"], y, z, p, q, skip)
            body = f"            {dest}\n"
            if action:
                body += f"            {action}\n"
            body += "            pins = release_pins(pins, IORQ | RD);\n"
            return body + goto

        # ---- I/O write -----------------------------------------------------
        if ts.kind == "iowrite_t1h":
            addr = addr_expr(ts.kw["ab"], y, z, p, q)
            return f"            pins = set_addr(pins, {addr});\n{goto}"
        if ts.kind == "iowrite_t2h_assert":
            db_tok = ts.kw["db"]
            data = "0" if db_tok in ("0", 0) else data_read_expr(db_tok, y, z, p, q)
            return (f"            pins = set_addr_data_assert(pins, get_addr(pins), {data}, IORQ | WR);\n"
                    f"{goto}")
        if ts.kind == "iowrite_tw_l_wait":
            return f"            if (asserted(pins, WAIT)) {{ return true; }}\n{goto}"
        if ts.kind == "iowrite_t3l_end":
            action = get_action(op.name, ts.kw["mci"], y, z, p, q, skip)
            body = ""
            if action:
                body += f"            {action}\n"
            body += "            pins = release_pins(pins, IORQ | WR);\n"
            return body + goto

        # ---- internal cycle -------------------------------------------------
        if ts.kind == "generic":
            action = get_action(op.name, ts.kw["mci"], y, z, p, q, skip)
            body = f"            {action}\n" if action else ""
            return body + goto

        # ---- overlapped fetch of the next instruction -----------------------
        if ts.kind == "overlapped":
            mci = ts.kw["mci"]
            action = get_action(op.name, mci, y, z, p, q, None)
            post_action = get_action(op.name, mci, y, z, p, q, None, is_post=True)
            body = f"            {action}\n" if action else ""
            prefix = ts.kw.get("prefix")
            if prefix == "ed":
                body += "            pins = begin_fetch_ed(pins);\n            return true;"
            elif prefix is not None:
                # Any other prefix value (cb/dd/fd) means this op should have
                # been excluded via SKIP_NAMES instead. Falling through to a
                # plain begin_fetch() here previously caused a real, silent
                # bug (see SKIP_NAMES' own comment) -- the prefix byte got
                # treated as a harmless no-op rather than failing loudly.
                raise ValueError(
                    f"{op.name}: unhandled prefix {prefix!r} -- add it to SKIP_NAMES "
                    f"until real dispatch for it exists, don't let it fall through silently"
                )
            else:
                body += "            pins = begin_fetch(pins);\n"
                if post_action:
                    body += f"            {post_action}\n"
                body += "            return true;"
            return body
        raise ValueError(f"unhandled T-state kind {ts.kind!r}")


def generate() -> str:
    ops = parse_opdescs()
    table = enumerate_opcodes(ops)

    gen = Generator()
    for idx in sorted(table):
        op, y, z, p, q = table[idx]
        gen.gen_op(idx, op, y, z, p, q)

    # CB-prefix payload steps: not part of the 0..512 opcode table (they're
    # dispatched into by z80.cpp's hand-written CB fetch machine cycle, which
    # decides between them based on the CB-suffix opcode's own z field), so
    # they get fresh alloc()'d step numbers instead of a fixed dispatch_index
    # -- exported below as named constants so hand-written code can reference
    # them without hardcoding magic numbers.
    cb_step = gen.gen_op(None, find_op(ops, "cb"), 0, 0, 0, 0)
    cbhl_step = gen.gen_op(None, find_op(ops, "cbhl"), 0, 0, 0, 0)

    body = "\n".join(gen.arms)
    return f"""\
// GENERATED FILE -- do not edit by hand.
// Produced by scripts/generate_z80_dispatch.py from vendor/chips/z80_desc.yml.
// Regenerate with: python scripts/generate_z80_dispatch.py
//
// Included directly into the body of Z80::dispatch_generated() in z80.cpp,
// which supplies the enclosing switch and the `pins` reference. Not a
// standalone translation unit -- it needs that function's scope.
//
// One switch case per HALF-T-state: every T-state is two cases, H then L
// (address valid on H, control lines assert on L). See z80.h's header
// comment for why that split exists.

/// Step number for the CB-prefix register-direct payload ("cb" in
/// z80_desc.yml) -- the hand-written CB fetch machine cycle jumps straight
/// here, not through the 0..512 opcode table.
#define ZX_CB_STEP {cb_step}
/// Same, for the "(HL)" form ("cbhl" in z80_desc.yml).
#define ZX_CBHL_STEP {cbhl_step}

{body}
"""


def main():
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(generate(), encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
