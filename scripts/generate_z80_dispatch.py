def get_action(name: str, mcycle_index: int, y: int, z: int, p: int, q: int,
               skip, is_post: bool = False) -> str | None:
    entry = ACTIONS.get(name)
    if entry is None:
        return None
    if callable(entry):
        # A plain-callable ACTIONS entry means "the action for this op's one
        # real (non-auto-appended-overlapped) mcycle" -- mci 0. Anything else
        # (the auto-appended trailing overlapped, or a `post_action` query)
        # genuinely has no action here.
        if mcycle_index != 0 or is_post:
            return None
        return entry(y, z, p, q, mcycle_index)
    key = "post" if is_post else mcycle_index
    fn = entry.get(key)
    if fn is None:
        return None
    try:
        return fn(y, z, p, q, mcycle_index, skip)
    except TypeError:
        return fn(y, z, p, q, mcycle_index)


