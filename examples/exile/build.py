"""Builds the Exile-like: generates its data, then assembles it with sjasmplus.

    python examples/exile/build.py

Writes output/exile.sna, with output/exile.sld beside it for source-level
stepping, output/exile.lst, and the symbols in output/exile.sym. Everything
in output/ is regenerated: what the game is built from is map.txt,
blocks.png and blocks.json, the sprite in sprites.py and the screen copy in
write_blit below -- never the .s and .bin they become.
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
OUT = HERE / "output"

sys.path.insert(0, str(HERE))
import blocks  # noqa: E402
import planet  # noqa: E402
import sprites  # noqa: E402

# The same search as examples/filmation's build: named, then the repo's copy,
# then PATH.
SJASMPLUS_CANDIDATES = [
    REPO / "tools" / "sjasmplus" / "sjasmplus.exe",
    REPO / ".venv-win" / "Scripts" / "sjasmplus.exe",
]

INSTALL_HELP = (
    "sjasmplus not found.\n"
    "Windows: download the prebuilt sjasmplus-<version>.win.zip from\n"
    "  https://github.com/z00m128/sjasmplus/releases and unzip it into\n"
    f"  {REPO / 'tools' / 'sjasmplus'} (or put sjasmplus.exe on PATH).\n"
    "Linux/macOS: build from source:\n"
    "  git clone https://github.com/z00m128/sjasmplus.git\n"
    "  cd sjasmplus && git submodule update --init --recursive && make"
)


def find_sjasmplus() -> str:
    named = os.environ.get("SJASMPLUS")
    if named and Path(named).is_file():
        return named
    for candidate in SJASMPLUS_CANDIDATES:
        if candidate.is_file():
            return str(candidate)
    on_path = shutil.which("sjasmplus")
    if on_path is not None:
        return on_path
    sys.exit(INSTALL_HELP)


def db_lines(data: bytes, per_line: int = 16) -> list[str]:
    return ["    db " + ", ".join(f"0x{b:02X}" for b in data[i:i + per_line])
            for i in range(0, len(data), per_line)]


def write_data() -> None:
    """output/data.s and output/map.bin: every table the game reads, in the
    order and alignment exile.s's memory map expects."""
    blockset = blocks.BlockSet()
    world = planet.read(blockset)
    (OUT / "map.bin").write_bytes(bytes(world))

    sprite_data = sprites.sprite_bytes()
    lines = [
        "; Generated by build.py from blocks.png, blocks.json and sprites.py.",
        "; Do not edit: edit those and rebuild.",
        "",
        f"; {len(blockset.legend)} blocks of {blocks.MAX_BLOCKS}. Page-aligned: a block's",
        "; 32 bytes are at the page plus number >> 3, low byte (number & 7) << 5.",
        "    ALIGN 256",
        "block_gfx:",
        *db_lines(blockset.graphics_bytes()),
        "    ALIGN 256",
        "block_mask:",
        *db_lines(blockset.mask_bytes()),
        "",
        "; The same, moved four pixels left (block_hi) and right (block_lo): BUF4's",
        "; columns are one's high half ORed with the next one's low.",
        "    ALIGN 256",
        "block_hi:",
        *db_lines(bytes((b << 4) & 0xFF for b in blockset.graphics_bytes())),
        "    ALIGN 256",
        "block_lo:",
        *db_lines(bytes(b >> 4 for b in blockset.graphics_bytes())),
        "    ALIGN 256",
        "block_cols:",
        *db_lines(blockset.column_bytes()),
        "",
        "; 0xFFFF >> n, n = 0..16: a column word's rows from n down.",
        "    ALIGN 64",
        "rows_from:",
        "    dw " + ", ".join(f"0x{0xFFFF >> n:04X}" for n in range(17)),
        "sprite_gfx:",
        *db_lines(sprite_data),
        "",
        "; Image * 8 + shift -> that image's rows at that shift.",
        "sprite_table:",
    ]
    image_size = 8 * sprites.H * 6
    for image in range(len(sprites.image_order())):
        lines.append("    dw " + ", ".join(
            f"sprite_gfx + {image * image_size + shift * sprites.H * 6}" for shift in range(8)))
    (OUT / "data.s").write_text("\n".join(lines) + "\n")


def write_blit() -> None:
    """output/blit.s: blit_view, the copy from the shown buffer to the
    screen, unrolled for a character row's eight lines.

    A line is two halves of sixteen bytes. Each half: SP to the buffer (IX
    for the first, IY for the second), POP eight register pairs -- the main
    four, then the alternate four -- then SP to the end of that half on the
    screen and PUSH them back in reverse. The screen addresses are written
    into the LD SP instructions once per character row, before its lines, so
    the lines themselves carry them as immediates; the page the shown buffer
    ends at is written into the lines' ring tests once per copy."""
    lines = [
        "; Generated by build.py (write_blit). Do not edit: edit build.py.",
        ";",
        "; blit_view -- copies the shown buffer's window to the screen's top",
        "; VIEW_LINES lines. Interrupts are off throughout, since SP points into",
        "; the buffer or the screen; the frame interrupt it spans is counted for it.",
        "blit_view:",
        "    call shown_buffer",
        "    ld a,c",
    ]
    lines += [f"    ld (blit_end_{i} + 1),a" for i in range(8)]
    lines += [
        "    ; IX = the window's first half, at the view's top line; IY = its",
        "    ; second, which starts 16 columns on, round the row's 32.",
        "    ld a,(cam_s4)",
        "    and 31",
        "    ld c,a",
        "    ld a,(ring_top)",
        "    call buffer_row",
        "    push hl",
        "    pop ix",
        "    ld a,(cam_s4)",
        "    add a,16",
        "    and 31",
        "    ld c,a",
        "    ld a,(ring_top)",
        "    call buffer_row",
        "    push hl",
        "    pop iy",
        "    ld hl,0x4000",
        "    ld (blit_base),hl",
        "    ld a,VIEW_H",
        "    ld (blit_rows),a",
        "    di",
        "    ld (blit_sp),sp",
        "blit_row:",
        "    ; This row's screen addresses into its lines' LD SPs: the end of each",
        "    ; line's first half, then of its second. Line i is 256 * i on.",
        "    ld hl,(blit_base)",
        "    ld de,16",
        "    add hl,de",
    ]
    for half in (1, 2):
        for i in range(8):
            lines.append(f"    ld (blit_{half}_{i} + 1),hl")
            if i < 7:
                lines.append("    inc h")
        lines += ["    ld a,h", "    sub 7", "    ld h,a"]
        if half == 1:
            lines.append("    add hl,de")
    for i in range(8):
        lines.append(f"    ; line {i}")
        for half, ptr in ((1, "ix"), (2, "iy")):
            lines += [
                f"    ld sp,{ptr}",
                "    pop af", "    pop bc", "    pop de", "    pop hl",
                "    exx", "    ex af,af'",
                "    pop af", "    pop bc", "    pop de", "    pop hl",
                f"blit_{half}_{i}:",
                "    ld sp,0                 ; patched: the half's end on the screen",
                "    push hl", "    push de", "    push bc", "    push af",
                "    exx", "    ex af,af'",
                "    push hl", "    push de", "    push bc", "    push af",
            ]
        lines += [
            "    ld bc,BUF_ROW",
            "    add ix,bc",
            "    add iy,bc",
            "    ld a,ixh",
            f"blit_end_{i}:",
            "    cp 0                    ; patched: the page the buffer ends at",
            f"    jr c,blit_ring_{i}",
            "    ld bc,-BUF_SIZE         ; round the ring",
            "    add ix,bc",
            "    add iy,bc",
            f"blit_ring_{i}:",
        ]
    lines += [
        "    ; The next character row: 32 on, or into the next third.",
        "    ld hl,(blit_base)",
        "    ld a,l",
        "    add a,32",
        "    ld l,a",
        "    jr nc,blit_same_third",
        "    ld a,h",
        "    add a,8",
        "    ld h,a",
        "blit_same_third:",
        "    ld (blit_base),hl",
        "    ld hl,blit_rows",
        "    dec (hl)",
        "    jp nz,blit_row",
        "    ld sp,(blit_sp)",
        "    ld hl,(frames)          ; the interrupt missed while it ran",
        "    inc hl",
        "    ld (frames),hl",
        "    ei",
        "    ret",
        "",
        "blit_sp:        dw 0",
        "blit_base:      dw 0",
        "blit_rows:      db 0",
    ]
    (OUT / "blit.s").write_text("\n".join(lines) + "\n")


def write_columns() -> None:
    """output/columns.s: the column fills' unrolled copies, one a line, for a
    block's sixteen lines -- four of them: BUF0 or BUF4, and a column held
    once or twice (columns 0..15 have a twin 32 on).

    A run enters at the line it starts at, through col_entries, and goes on
    down block after block: at a block's end it counts one off B' and, while
    any are left, takes the next block's pointers off HL' -- four bytes a
    block, its bytes for this column, then BUF4's other bytes -- and goes
    round again. A run that ends part way down a block stops at a RET
    fill_column puts in, through col_stops. Between lines 7 and 8 the pointer
    into the block's bytes jumps from the top half's to the bottom half's,
    eight on: that belongs to line 8, so a run entering there skips it and a
    run stopping there stops before it.

        DE  the block's bytes for this column (block_gfx, or block_hi for BUF4)
        IY  BUF4 only: the next column's, block_lo, at the block's first line
        HL  where the line goes (a column held once), or IX (held twice)
        BC  BUF_ROW"""
    variants = [
        ("col0_once", False, False),
        ("col0_twice", False, True),
        ("col4_once", True, False),
        ("col4_twice", True, True),
    ]
    lines = ["; Generated by build.py (write_columns). Do not edit: edit build.py.", ""]
    for name, shifted, twin in variants:
        lines.append(f"{name}:")
        for p in range(16):
            if p == 8:
                lines += [f"{name}_stop_8:", "    ld a,e", "    add a,8", "    ld e,a", f"{name}_entry_8:"]
            else:
                lines.append(f"{name}_entry_{p}:")
            lines += ["    ld a,(de)", "    inc e"]
            if shifted:
                lines.append(f"    or (iy + {p if p < 8 else p + 8})")
            if twin:
                lines += ["    ld (ix + 0),a", "    ld (ix + 32),a", "    add ix,bc"]
            else:
                lines += ["    ld (hl),a", "    add hl,bc"]
        lines += [
            "    ; The block's end: another, or done.",
            "    exx",
            "    dec b",
            f"    jr z,{name}_done",
            "    ld e,(hl)",
            "    inc hl",
            "    ld d,(hl)",
            "    inc hl",
        ]
        if shifted:
            lines += ["    ld c,(hl)", "    inc hl", "    ld a,(hl)", "    inc hl",
                      "    ld iyl,c", "    ld iyh,a"]
        else:
            lines += ["    inc hl", "    inc hl"]
        lines += ["    push de", "    exx", "    pop de", f"    jp {name}_entry_0",
                  f"{name}_done:", "    exx", "    ret", ""]
    lines.append("; Variant * 16 + first line -> where a run enters.")
    lines.append("col_entries:")
    for name, _, _ in variants:
        lines.append("    dw " + ", ".join(f"{name}_entry_{p}" for p in range(16)))
    lines.append("; Variant * 16 + the line a run stops before -> where the RET goes.")
    lines.append("col_stops:")
    for name, _, _ in variants:
        stops = [f"{name}_entry_{p}" if p != 8 else f"{name}_stop_8" for p in range(16)]
        lines.append("    dw " + ", ".join(stops))
    (OUT / "columns.s").write_text("\n".join(lines) + "\n")


def assemble(sjasmplus: str) -> None:
    cmd = [
        sjasmplus,
        "--nologo",
        "--fullpath",
        f"--sld={OUT / 'exile.sld'}",
        f"--lst={OUT / 'exile.lst'}",
        f"--sym={OUT / 'exile.sym'}",
        "exile.s",
    ]
    result = subprocess.run(cmd, cwd=HERE)
    if result.returncode != 0:
        sys.exit(result.returncode)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    try:
        write_data()
    except ValueError as e:
        sys.exit(f"error: {e}")
    write_blit()
    write_columns()
    assemble(find_sjasmplus())
    print(f"wrote {OUT / 'exile.sna'}")


if __name__ == "__main__":
    main()
