"""Builds the isoblocks demo: sjasmplus, from demo/demo.s -> output/demo.z80.

Three things are generated first, into output/, from files that are edited by
hand:

- view_tables.s, from isogeom.py: each view's three map steps, where its
  first cell is from the focus, and the limits that keep the view on the map.
  The same module is the model check_render.py draws with, so the engine and
  the model cannot disagree about the geometry.
- blocks_gen.s, from art/blocks.png and art/blocks.json: a drawer per block
  picture, unrolled -- a store for every byte of the block that is solid, an
  AND and an OR for every byte that is part clear, nothing at all for a byte
  that is wholly clear.
- map.bin, from maps/test.json: the boxes rasterised to 16K of cells.

sjasmplus writes all eight RAM banks (SAVEDEV), the view from $4000 as the
engine runs (SAVEBIN, for check_render.py) and the SLD; ../filmation/z80file.py
wraps the banks as a 128K .z80 that starts at `start`.

    python build.py
"""
