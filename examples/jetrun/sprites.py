NAMES = list(FRAMES)


def rows(name: str, mirror: bool) -> list[str]:
    lines = [line for line in FRAMES[name].strip("\n").split("\n")]
    assert len(lines) == HEIGHT and all(len(line) == WIDTH for line in lines), name
    return [line[::-1] for line in lines] if mirror else lines


def ink_and_mask(lines: list[str]) -> tuple[list[int], list[int]]:
    """Each row's ink and opaque pixels as 16-bit numbers, bit 15 leftmost.
    The opaque area is the ink grown by one pixel in all eight directions."""
    ink = [sum(1 << (15 - x) for x, ch in enumerate(line) if ch == "#") for line in lines]
    opaque = []
    for y in range(HEIGHT):
        grown = 0
        for dy in (-1, 0, 1):
            if 0 <= y + dy < HEIGHT:
                r = ink[y + dy]
                grown |= r | (r << 1) | (r >> 1)
        opaque.append(grown & 0xFFFF)
    return ink, opaque


def frame_bytes(frame: int, shift: int) -> bytes:
    """A frame at a shift: per row, mask and ink for each of three bytes --
    mask, ink, mask, ink, mask, ink -- top row first. A mask bit set keeps the
    screen's pixel; the game draws (screen AND mask) OR ink."""
    name = NAMES[frame % 4]
    ink, opaque = ink_and_mask(rows(name, frame >= 4))
    out = bytearray()
    for y in range(HEIGHT):
        i = ink[y] << (8 - shift)
        o = opaque[y] << (8 - shift)
        for b in range(3):
            sh = 16 - 8 * b
            out.append(~(o >> sh) & 0xFF)
            out.append((i >> sh) & 0xFF)
    return bytes(out)


