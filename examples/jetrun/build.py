"""Build Jetrun: generate its data from the world and the model, then
assemble it with sjasmplus.

    python examples/jetrun/build.py

Writes output/data.s (every table and constant the game reads, generated:
never edit it), then output/jetrun.sna to run, output/jetrun.bin (memory
from 0x4000, for check.py), output/jetrun.sld for source-level stepping and
output/jetrun.sym. What the game is built from is world/*.json, the
geometry in world.py, the screen layout in model.py, the physics constants in
game.py and the art in sprites.py: the constants here are read from those
modules, so the Z80 and the Python model cannot disagree about them.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
OUT = HERE / "output"
sys.path.insert(0, str(HERE))
import game as G      # noqa: E402
import model as M     # noqa: E402
import sprites as S   # noqa: E402
import world as W     # noqa: E402

SJASMPLUS_CANDIDATES = [
    REPO / "tools" / "sjasmplus" / "sjasmplus.exe",
    REPO / ".venv-win" / "Scripts" / "sjasmplus.exe",
]

STACK_TOP = 0x8000
NEWLINE = chr(10)
CODE = 0x8000


def find_sjasmplus() -> str:
    named = os.environ.get("SJASMPLUS")
    if named and Path(named).is_file():
        return named
    for candidate in SJASMPLUS_CANDIDATES:
        if candidate.is_file():
            return str(candidate)
    on_path = shutil.which("sjasmplus")
    if on_path:
        return on_path
    sys.exit("sjasmplus not found: see examples/exile/build.py's note on installing it")


def dw(names: list[str], per_line: int = 8) -> list[str]:
    return ["    dw " + ", ".join(names[i:i + per_line]) for i in range(0, len(names), per_line)]


def db(values, per_line: int = 16) -> list[str]:
    values = [v & 0xFF for v in values]
    return ["    db " + ", ".join(f"0x{v:02X}" for v in values[i:i + per_line])
            for i in range(0, len(values), per_line)] or ["    ; (none)"]


def write_data(world: W.World) -> None:
    empty = [name for name in world.tile_names if not world.pieces(name)]
    if not empty:
        sys.exit("tiles.json needs an empty tile: Cyberun's renderer shows it below the map")
    lines = [
        "; Generated by build.py from world/*.json, world.py, model.py, game.py and",
        "; sprites.py. Do not edit: edit those and rebuild.",
        "",
        f"PAGE_W          equ {W.PAGE_W}",
        f"PAGE_H          equ {W.PAGE_H}",
        f"MAP_W           equ {world.width}",
        f"MAP_H           equ {world.height}",
        f"EMPTY_TILE      equ {world.tile_number[empty[0]]}",
        f"WORLD_W         equ {world.world_w}",
        f"WORLD_H         equ {world.world_h}",
        f"MOVE            equ {W.MOVE}",
        f"PLAY_LEFT       equ {M.PLAY_LEFT}",
        f"PLAY_TOP        equ {M.PLAY_TOP}",
        f"PLAY_W          equ {M.PLAY_W}",
        f"PLAY_H          equ {M.PLAY_H}",
        f"FIRST_COLUMN    equ {M.FIRST_COLUMN}",
        f"LAST_COLUMN     equ {M.LAST_COLUMN}",
        f"SPRITE_H        equ {S.HEIGHT}",
        f"BODY_LEFT       equ {G.BODY_LEFT}",
        f"BODY_RIGHT      equ {G.BODY_RIGHT}",
        f"BODY_TOP        equ {G.BODY_TOP}",
        f"BODY_BOTTOM     equ {G.BODY_BOTTOM}",
        f"GRAVITY         equ 0x{G.GRAVITY:04X}",
        f"THRUST          equ 0x{G.THRUST:04X}",
        f"ACCEL           equ 0x{G.ACCEL:04X}",
        f"WALK            equ 0x{G.WALK:04X}",
        f"MAX_SPEED       equ 0x{G.MAX_SPEED:04X}",
        f"CLIMB           equ {G.CLIMB}",
        f"ASTRONAUT_ATTR  equ 0x{G.ASTRONAUT_ATTR:02X}",
        f"GROUND_ABOVE    equ 0x{world.surface_attr:02X}",
        f"GROUND_BELOW    equ 0x{world.cavern_attr:02X}",
        f"CAVERN_ROW      equ {world.cavern_row}",
        f"CENTRE_X        equ {G.CENTRE_X}",
        f"CENTRE_Y        equ {G.CENTRE_Y}",
        f"VIEW_STEP_Y     equ {G.VIEW_STEP_Y}",
        f"CEILING         equ {G.CEILING}",
        f"STACK_TOP       equ 0x{STACK_TOP:04X}",
        "",
    ]
    # Where a new life starts: the model's own start.
    game = G.Game(world)
    game.start()
    lines += [
        "start_state:",
        f"    db 0x{game.ax & 0xFF:02X}",
        f"    dw {game.ax >> 8}",
        f"    db 0x{game.ay & 0xFF:02X}",
        f"    dw {game.ay >> 8}",
        f"    dw {game.view_x}, {game.view_y}",
        "",
        "; The map: a tile number for each page, row by row. Cyberun's renderer",
        "; reads it too, as its map rows 1 on (its row 0 is the sky above).",
        "world_map:",
        *db([world.tile_number[name] for row in world.rows for name in row], world.width),
        "",
        "; Where each row of the map starts.",
        "map_rows:",
        *dw([f"world_map + {r * world.width}" for r in range(world.height)]),
        "",
        "; Each tile's record as Cyberun's renderer reads it (world.cyberun_record).",
        "tile_table:",
        *dw([f"tile_{n}" for n in range(len(world.tile_names))]),
    ]
    for n, name in enumerate(world.tile_names):
        lines.append(f"tile_{n}:                 ; {name}")
        lines.extend(db(world.cyberun_record(name)))
    lines += ["", "; Each tile's crossings for the full render: a count, then per floor or",
              "; ceiling x, y (play-area pixels in the page), direction, steps.",
              "toggle_table:",
              *dw([f"toggle_{n}" for n in range(len(world.tile_names))])]
    for n, name in enumerate(world.tile_names):
        runs = world.surfaces(name)
        lines.append(f"toggle_{n}:               ; {name}")
        lines.append(f"    db {len(runs)}")
        for s in runs:
            if s.steps > 255:
                sys.exit(f"tile {name!r}: a surface of {s.steps} steps does not fit the full render's byte")
            lines.append(f"    dw {s.x}, {s.y + W.CROSS_DY}")
            lines.append(f"    db {s.toggle}, {s.steps}")
    lines += ["", "; The full render's directions: dx, dy (signed).", "toggle_steps:"]
    for dx, dy in W.TOGGLE_DIRECTIONS:
        lines.append(f"    db {dx}, {dy & 0xFF}")
    lines += ["", "; Each direction's surface row in each column of a step.", "surface_offsets:"]
    for dx, dy in W.TOGGLE_DIRECTIONS:
        lines.extend(db([W.surface_offset(dx, dy, i) if i < dx else 0 for i in range(16)]))
    # The view keeps the sprite at CENTRE_X on a byte boundary, and it never
    # lags behind across (its 2-pixel step is the astronaut's top speed), so
    # the sprite is only ever drawn at shift 0: only that is built, and every
    # entry points at it. (check.py's model draws at whatever shift the place
    # asks for, so a sprite off a byte boundary would show there.)
    assert (M.PLAY_LEFT + G.CENTRE_X) % 8 == 0 and G.MAX_SPEED <= W.MOVE << 8
    lines += ["", "; The astronaut: frame * 8 + shift -> its bytes (shift 0 only: see build.py).", "sprite_frames:"]
    lines.extend(dw([f"frame_{f}_0" for f in range(S.FRAME_COUNT) for s in range(S.SHIFT_COUNT)]))
    for f in range(S.FRAME_COUNT):
        lines.append(f"frame_{f}_0:")
        lines.extend(db(S.frame_bytes(f, 0), 6))
    OUT.mkdir(exist_ok=True)
    (OUT / "data.s").write_text(NEWLINE.join(lines) + NEWLINE, encoding="utf-8")


def assemble(defines: list[str]) -> None:
    result = subprocess.run(
        [find_sjasmplus(), "--nologo", "--fullpath", "--sld=output/jetrun.sld",
         "--sym=output/jetrun.sym", "--lst=output/jetrun.lst"]
        + [f"-D{name}" for name in defines] + ["jetrun.s"],
        cwd=HERE, capture_output=True, text=True)
    sys.stdout.write(result.stdout)
    sys.stderr.write(result.stderr)
    if result.returncode != 0:
        sys.exit("sjasmplus failed")
    counts = re.search(r"Errors: (\d+), warnings: (\d+)", result.stdout + result.stderr)
    if not counts or counts.group(1) != "0":
        sys.exit("sjasmplus found errors")
    if counts.group(2) != "0":
        sys.exit("sjasmplus warned: fix it")


def free_memory() -> int:
    """Bytes between the end of the game and the interrupt's jump."""
    table = {}
    for line in (OUT / "jetrun.sym").read_text().splitlines():
        if ": EQU " in line:
            name, value = line.split(": EQU ")
            table[name.strip()] = int(value, 16)
    return table["IM2_JUMP"] - table["end_of_game"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--free-run", action="store_true",
                        help="start each pass as soon as the last is done, not every two frames")
    parser.add_argument("--border-timing", action="store_true",
                        help="colour the border by the stage of the pass running (jetrun.s)")
    args = parser.parse_args()
    W.check_schemas()
    world = W.load()
    world.validate()
    write_data(world)
    assemble((["FREE_RUN"] if args.free_run else []) + (["BORDER_TIMING"] if args.border_timing else []))
    print(f"wrote {OUT / 'jetrun.sna'}; {free_memory()} bytes free")


if __name__ == "__main__":
    main()
