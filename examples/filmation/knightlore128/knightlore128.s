; The stack grows down from the top of bank 2, so the code has to stop short of
; what it reserves there. This is the check that was missing when the player
; pushed the top of the image into the stack.
image_end:
                    ASSERT  $ <= STACK_TOP - STACK_RESERVE
                    DISPLAY "code            $8000..", /H, image_end, "   free below the stack: ", /D, STACK_TOP - STACK_RESERVE - image_end

; ---------------------------------------------------------------------------
; Code that runs between games rather than during one: the end screens and
; their tunes, what plays the tunes, and the menu. It was up with the rest of
; the code on the 48K. On the 128K that space went to the stack, and this is
; cold enough not to mind contended memory, so it goes on the end of the data
; in the $6000 region. It is assembled down here, after the engine, because
; menu.s uses sprite_width_class, a macro engine/sprite.s brings in.
                    ORG     room_data_end
cold_start:
                    INCLUDE "end.s"             ; its tunes and their notes, then
                    INCLUDE "../engine/tune.s"  ; what plays them
                    INCLUDE "menu.s"
                    INCLUDE "end_at.s"          ; where both of them put a character
cold_end:
                    ASSERT  cold_end <= $7400   ; clear of the view buffer
                    DISPLAY "data, cold code $6000..", /H, cold_end, "   free: ", /D, $7400 - cold_end

; ---------------------------------------------------------------------------
; The room page, in bank 0 at $C000: the bank that stays paged in for the whole
; of play, since every turn draws from it. Bank 0 is uncontended on every 128K
; model, the +2A and +3 included. The resident sprites are assembled into it
; for good; room_page, after them, is where each room's own are loaded -- see
; room_page.s.
                    ORG     $C000
sprite_start:
					INCLUDE "sprite_data.s"
sprite_end:

; The templates every room is built from, and the tables that go with them. They
; were in the $6000 region; Pentagram's doubled them, and that region is full.
; Bank 0 is paged in all the time a room is being built and played, and nothing
; reads a template while room_find or room_page_fill has another bank in, so
; they can sit here, ahead of the room page. If the page runs short, the plan's
; next step is to copy only the templates a room names out of bank 4, as
; room_find copies its record -- see ../engine/memory-128k.md.
                    INCLUDE "room_data.s"
room_templates_end:
                    ALIGN   4
room_page:
                    ASSERT  room_page + ROOM_PAGE_MOST <= $10000
                    DISPLAY "room page, bank 0: resident to ", /H, room_page, ", the fullest room to ", /H, room_page + ROOM_PAGE_MOST, "   free: ", /D, $10000 - room_page - ROOM_PAGE_MOST

; ---------------------------------------------------------------------------
; The rooms, in bank 4 at $C000. Only room_find reads them, with bank 4 paged
