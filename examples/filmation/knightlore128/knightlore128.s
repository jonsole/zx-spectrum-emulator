; Knight Lore 128K. Where everything goes, bank by bank:
;
;   bank 5, $4000   the screen; the room builder at $5B00; the room templates,
;                   the tables and the cold code (the menu, the end screens)
;                   from $6000; the view buffer, the object pool and the
;                   aligned tables from $7400
;   bank 2, $8000   the code that runs every turn, the rotation arena, and the
;                   stack at the top, below $C000
;   bank 0, $C000   the room page, paged in for the whole of play: the
;                   resident sprites, then the room being played's own
;   bank 4, $C000   the rooms, and what each loads into the room page; paged
;                   in only while a room is looked up and loaded
;   bank 1, $C000   the library: the sprites loaded room by room (3 and 7
;                   follow when it outgrows one bank)
;
; Banks 3, 6 and 7 are empty so far. ../engine/memory-128k.md is the plan for
; them, and README.md says how far it has got. The device's default mapping is
; the 128K's own at power-on -- banks 5, 2 and 0 -- and everything is
; assembled into it except the rooms and the library, which MMU puts in their
; own banks.
					DEVICE ZXSPECTRUM128


					ORG	0x8000

; The view buffer is a window, not a screen: everything that intersects the
; area a moved object disturbed is composited here, then copied out in one
; go. Its shape is therefore the hard limit on how big a single object can
; be, and both dimensions have to clear the whole sprite set:
;
;   widest sprite   5 bytes, and a sprite that is not byte-aligned spans one
;                   column more than its own width -- so 6 columns
;   tallest sprite  64 rows (the castle door arch; the forest one is 52)
;
; 8 x 64 = 512 bytes covers both with the stride a power of two, which is
; what makes the row address a shift rather than a multiply. Six would be
; tight enough to work and no cheaper: 6 x 64 is 384, still over a page, so
; the second page has to be handled either way, and the multiply-by-6 costs
; more than the multiply-by-8 saves. The padding from the sprite's width out
; to the stride is what the extra two columns actually cost -- see the row
; advance in sprite_blit.
VIEW_BUF_WIDTH		EQU		8

; The buffer spans two pages, so the blit cannot address it with `ld d,high
; view_buffer` plus `inc e` throughout. Rows are 8 bytes on an 8-byte
; boundary, so no row straddles the page break and only the increments that
; can land on a row boundary have to carry into D -- which is the last one
; of each row, plus the row advance itself. Everything inside a row stays
; `inc e`. Knight Lore has no limit of this kind at all, because its buffer
; IS the screen; ours is a small window, and this is what that costs.
VIEW_BUF_ROWS		EQU		512 / VIEW_BUF_WIDTH

; The stack, in UNCONTENDED memory. Whatever loaded the game leaves SP where
; its own stack was -- 0x5D56, in the .sna this used to be built as -- which is
; inside the ULA-contended 0x4000-0x7FFF window, so on real hardware
; every call and return there pays a contention delay -- a few hundred
; T-states a frame for nothing. Everything that runs every turn lives above
; 0x8000 -- the code, the sprite data and the rotate table -- and what sits
; below it is read rarely or is cheap to reach: see the regions further down.
;
; It starts at the top of bank 2 -- SP = $C000, so the first push lands at
; $BFFE -- and STACK_RESERVE is kept clear below it. On the 48K it was at the
; very top of memory. On the 128K that is the bank that pages, and a RET with
; another bank in would read its address from that bank.
;
; The reserve is measured, not guessed: the bytes below the stack are filled
; with a pattern, the game is played through the rooms with everything in them
; moving -- the pot, a portcullis, collapsing blocks, pickups, a death, a
; change of light and a new game -- and the untouched bytes counted afterwards.
; That says 34, where it said 26 before the sounds and the panel, which nest
; deeper. Anything that adds to the deepest call chain wants re-measuring.
STACK_TOP			EQU		0xC000
STACK_RESERVE		EQU		48		; 34 used, 14 spare

; ---------------------------------------------------------------------------
; The castle's tables, in contended memory.
;
; The pixel adjustments Knight Lore's own code would have computed, and the
; tables that go with the panel, the font and the charms. The rooms themselves
; are in bank 4, and the templates they are built from in bank 0 -- see the
; foot of this file. Little of it is touched except when a room is built, so
; it costs nothing to leave it where the ULA fights the CPU for it -- which is
; also where the game itself kept it.
;
; room_data.s is generated by rooms_source.py from rooms.json, specials_gen.s
; by specials_source.py from specials.json, and sprite_adj_gen.s by
; sprite_source.py from graphic_map.json, whose nudges adj.py harvests from a
; running game. None of them is hand-written; all three read the JSON the
; repository carries, not the packed files kl_extract.py first pulled them
; out of.
                    ORG     $6000
                    INCLUDE "panel_data.s"
                    INCLUDE "sprite_adj_gen.s"
                    INCLUDE "graphics_gen.s"   ; GFX_* -- generated from graphics.json

; The game's own font: forty 8x8 characters, which is all the text Knight Lore
; has. Digits first and then letters, no lower case and no punctuation beyond
; what a word needs -- so a hex digit is its own character index and needs no
; translating, which is the whole of why printing a room number is six
; instructions. kl_extract.py pulls it from $6108, immediately in front of the
; room tables; the game's own object walk uses it as the end of its object
; table for the same reason.
;
; font.s is generated from the font sheet, font.png and font.json, which is
; where the artwork lives -- see font_sheet.py and font_source.py. It opens
; the label `font` that print_char reaches for.
                    INCLUDE "font.s"

; The collectables: where each of the thirty-two starts, the order the wizard
; wants them in, and which graphic each row has been dealt -- see special.s.
; kl_extract.py pulls the first two out of the game, as it does the font, and
; specials_source.py turns specials.json back into assembler. All four labels
; come out of that one file: the two that hold data and the two that only
; reserve room, because special_init copies the first over the second in one
; LDIR and nothing may come between them.
                    INCLUDE "specials_gen.s"

; The one buffer every deferred rotation goes through, moved down here for the
; same reason -- see shift.s for what it is and how it is sized.
shift_shared:       DS      SHIFT_SHARED_SIZE

; The sound effects, which only choose what to play -- see sound.s.
                    INCLUDE "sound_fx.s"
                    INCLUDE "monster_gate.s"    ; where the trimmed index left room

