; ---------------------------------------------------------------------------
; Building a room, down where the ROM keeps its system variables.
;
; $5B00 to $5FFF is the printer buffer and the system variables, and none of it
; is wanted: interrupts are off for good, nothing here calls the ROM, and the
; stack is up at STACK_TOP. It is contended, so what goes here has to be code
; that does not run every turn -- and building a room is the definition of
; that.
;
; Pentagram's builder differs from Knight Lore's in one place that matters:
; leaving a room. Knight Lore computes the next room arithmetically on a 16x16
; grid. Pentagram cannot -- its map has forty distinct deltas and thirteen
; different ones for a single doorway direction -- so the destination is read
; from the room record instead. Its twelve doorway templates are scenery
; indices 0-7 and 24-27, with the side in `index & 3` as 0=N, 1=E, 2=S, 3=W,
; the same convention Knight Lore uses. The destination byte is the authority,
; not the template: one south doorway is an exit in twenty-eight rooms and
; blocked in one.
                    ORG     $5B00
                    INCLUDE "room_build.s"
                    INCLUDE "../engine/room.s"
                    INCLUDE "quest_ram.s"
                    INCLUDE "busy.s"
                    INCLUDE "sound_fx.s"
                    INCLUDE "menu.s"
room_code_end:
                    ASSERT  room_code_end <= $6000
                    DISPLAY "room builder     $5B00..", /H, room_code_end, "   free: ", /D, $6000 - room_code_end

; ---------------------------------------------------------------------------
; Reservations, in the gap between the data and the code.
;
; The view buffer is aligned to its own size, so a row start is a multiple of
; the stride in both pages and `high view_buffer` is even -- the row address
; folds its top bit into D with a single `rl d`, which needs an even base.
                    ORG     $7400
                    ALIGN   512
view_buffer:        DS      VIEW_BUF_ROWS * VIEW_BUF_WIDTH

; The object pool. A room owns all of it: the builder refills it from the
; start, so nothing survives a room change. 43 is the fullest room in the game
; -- room 87 -- and rooms_source.py emits it as ROOM_MAX_OBJECTS, counted by
; expanding every scenery chain and every object entry's repeat count. It is
; read from there rather than kept here, so it cannot drift from the data.
; One more than the fullest room needs, so that even there something can be
; put down or come out of the well -- the original keeps 48 slots for a room
; and what persists in it, and the fullest room has 43.
ROOM_SLOTS          EQU     ROOM_MAX_OBJECTS + 1 ; what room_add may fill
POOL_SLOTS          EQU     ROOM_SLOTS + EXTRA_SLOTS ; and what falls or is fired
                    ALIGN   32
room_objects:
                REPT    POOL_SLOTS
                    ALIGN   32
                    object_record   0,      0,              0, 0, 0
                ENDR
                    ; object_record lays down only the first twenty bytes of a
                    ; record; the ALIGN in front of the next one gives it the
                    ; rest. The last one has no next one, so it needs this or
                    ; its final twelve bytes are whatever follows the pool.
                    ALIGN   32
                    ASSERT  $ == room_objects + POOL_SLOTS * ROOM_STRIDE

                    ALIGN   256
; Every byte with its bits the other way round, for mirroring a sprite.
bit_reverse_table:
                    bit_reverse_bytes

; sprite_table is read as `ld h,(high sprite_table)/2 / ld l,a / add hl,hl`, so
; its page has to be even: a 512 boundary, not merely a 256 one. Pentagram
; names 172 graphics rather than 256, but the table is still 512 bytes -- the
; entries past the game's own simply hold zero.
                    ALIGN   512
                    INCLUDE "sprite_table.s"

pool_end:
                    ASSERT  $ <= $8000      ; still inside the gap
                    DISPLAY "buffer and pool $7400..", /H, pool_end, "   free: ", /D, $8000 - pool_end

