; Pentagram on the Filmation engine in ../engine, laid out the way
; ../knightlore/knightlore.s lays out Knight Lore. The engine is shared
; unchanged; what differs is this file, the game code, and the data.
;
; NOT YET COMPLETE. The engine names a list of things a game has to supply
; -- mover_tbl, walker_player, the BEHAVIOUR_ and CHARACTER_ equates, a
; character_steer, a redraw_hook -- and Pentagram has none of them yet. The
; includes for those are listed below and commented out, each with what still
; has to exist. What this file IS good for now is the memory map: the regions,
; the alignments the engine insists on, and the ASSERT/DISPLAY pairs that
; report what is left. Uncomment as the files arrive.
;
; ---------------------------------------------------------------------------
; How Pentagram differs from Knight Lore, measured rather than assumed:
;
;   sprites        87, widest 40 pixels (5 bytes), tallest 55 rows
;                  Knight Lore: 103, widest 5 bytes, tallest 64 rows
;   graphics       172, against 256 -- but sprite_table still fills 512 bytes,
;                  because the engine reaches it by doubling a pre-halved base
;                  and needs the alignment either way
;   rooms          139, against 128
;   fullest room   43 objects (room 87), against 36 -- so the pool is 1,376
;                  bytes where Knight Lore's is 1,152 plus its collectables
;   room data      4,055 bytes, against 2,986 -- Pentagram keeps a destination
;                  room number against every scenery entry, which is what buys
;                  it a map that is not a grid
;   font           43 characters, 344 bytes, against 40 and 320
;   sprite data    13,798 bytes, against 15,572
;
; So Pentagram is about 1,100 bytes heavier in room data and 224 in the pool,
; and about 1,800 lighter in sprites. Close to a wash overall, but distributed
; differently -- the contended region below $8000 is the one under pressure,
; not the code region above it. Knight Lore finished with 3, 2, 4 and 6 bytes
; free in its four regions; this one starts from a blank sheet and should not
; be allowed to end up there.

					ORG	0x8000

; The view buffer is a window, not a screen: everything that intersects the
; area a moved object disturbed is composited here, then copied out in one go.
; Its shape is the hard limit on how big a single object can be, and both
; dimensions have to clear the whole sprite set:
;
;   widest sprite   5 bytes, and a sprite that is not byte-aligned spans one
;                   column more than its own width -- so 6 columns
;   tallest sprite  55 rows
;
; Pentagram's tallest sprite is 55 where Knight Lore's is 64, so 8 x 64 is
; more than it needs -- 8 x 56 would cover it. It is kept at 64 anyway: the
; row address folds into D with a single `rl d`, which wants the stride a
; power of two and the base even, and 8 x 64 = 512 gives both. Dropping to 56
; rows saves 64 bytes and costs the alignment, which is not a good trade.
VIEW_BUF_WIDTH		EQU		8
VIEW_BUF_ROWS		EQU		512 / VIEW_BUF_WIDTH

; The stack, in UNCONTENDED memory, growing down from the top: SP = 0, so the
; first push lands at $FFFE. STACK_RESERVE is kept clear below it.
;
; Knight Lore's reserve is 48, measured by filling the bytes below the stack
; with a pattern, playing through rooms with everything moving, and counting
; what stayed untouched -- 34 used, 14 spare. Pentagram's call chains are not
; Knight Lore's, so this figure is inherited, not measured, and wants
; re-measuring the same way once the game runs. Until then it is a guess with
; Knight Lore's margin on it.
STACK_TOP			EQU		0x0000
STACK_RESERVE		EQU		48		; inherited from Knight Lore; NOT measured here

; ---------------------------------------------------------------------------
; The game's data, in contended memory.
;
; Every room, the templates they are built from, and the font. None of it is
; touched except when a room is built, so it costs nothing to leave it where
; the ULA fights the CPU for it -- which is where Pentagram itself kept it.
;
; room_data.s is generated by rooms.py from rooms.json, which rooms.py writes
; from room_data.bin, which pg_extract.py takes out of your own copy of the
; tape. font.s comes from font.png/font.json by way of font_source.py. None of
; them is hand-written.
                    ORG     $6000
                    INCLUDE "room_data.s"
                    INCLUDE "font.s"

; The one buffer every deferred rotation goes through -- see ../engine/shift.s.
shift_shared:       DS      SHIFT_SHARED_SIZE

                    INCLUDE "sound_data.s"
                    INCLUDE "sound_tune.s"
room_data_end:
                    ASSERT  room_data_end <= $7400      ; clear of the view buffer
