PLAYER_LEGS_GFX     EQU     16
PLAYER_BODY_GFX     EQU     32
PLAYER_U            EQU     128         ; the middle of the room, where the game
PLAYER_V            EQU     128         ; starts him (plyr_spr_init_data)
PLAYER_FACING       EQU     0           ; -U, up and left

player:             walking_character PLAYER_LEGS_GFX, PLAYER_BODY_GFX, PLAYER_FACING

; How many times he can die and carry on. Knight Lore sets five and the start
; of the game takes one, through the same lose_life every death goes through,
; so the panel reads four; the game is over when a death would take the count
; below nothing. The potion that is not wanted gives one back.
PLAYER_LIVES        EQU     4
player_lives:       DB      PLAYER_LIVES

; What he is doing: walking about, dying, or coming back. The two sparkling
; states are his graphics running through Knight Lore's own frames -- 112 to
; 119 on the way out, a frame a turn, and 120 to 127 on the way back, a frame
; every other turn -- during which nothing he presses counts.
PLAYER_ALIVE        EQU     0
PLAYER_DYING        EQU     1
PLAYER_APPEARING    EQU     2
PLAYER_CHANGING     EQU     3                   ; between man and wolf -- see day_step
PLAYER_DEATH_GFX    EQU     112
PLAYER_APPEAR_GFX   EQU     120
player_state:       DB      PLAYER_APPEARING

; Set when he touches something deadly -- see object_touched -- and read at the
; top of his next turn, as the game reads its bit 6 in upd_player_bottom.
player_touched:     DB      0

; --- day and night -----------------------------------------------------------
;
; Knight Lore's clock is the sun, or the moon, crossing the window in the panel:
; a pixel every eighth turn from x = $B0, and at $E1 the one gives way to the
; other and starts back at $B0 -- print_sun_moon and toggle_day_night, at $C397
; and $C3FF. Forty-nine pixels at eight turns each is 392 turns to a day and as
; many again to a night. Every change of light asks the knight to change too, and
; every dawn is a day gone; the fortieth is the end of the game.
;
; The clock counts turns, as the game's does, so a day is as many steps long as
; it was -- which at our pace is about eleven seconds, where Knight Lore's
; slower turns made it nearer thirty. SUN_TURNS is the knob.
;
; There is no window to watch it in yet; the day number is printed in the top
; corner beside the lives, and the werewolf says the rest.
SUN_TURNS           EQU     8                   ; a power of two
SUN_RISE            EQU     $B0
SUN_SET             EQU     $E1
DAYS_ALLOWED        EQU     $40                 ; in BCD, as the game counts
PLAYER_WOLF         EQU     $20                 ; what the wolf adds to the knight's
                                                ; graphics: legs 48, body 64
PLAYER_CHANGE_GFX   EQU     92                  ; 92 to 95, the twinkle between
PLAYER_CHANGE_TURNS EQU     8                   ; ...shown this many times,
PLAYER_HIDDEN_GFX   EQU     1                   ; with nothing on top of it

sun_x:              DB      SUN_RISE
night:              DB      0                   ; PLAYER_WOLF by night
days:               DB      0                   ; BCD

; Non-zero when the light has changed and the knight has not changed with it,
; and while he is changing, the twinkles still to come. transform_flag_graphic,
; less the graphic: the game keeps his legs' graphic there to XOR the wolf into
; at the end, and ours changes the bases the frames are worked out from instead.
player_change:      DB      0


; The side he came into this room by, or $FF, and where he stood once he was
; in, so that dying puts him back in the doorway he entered by. Knight Lore does
; the same with a copy of his whole record taken on the way in
; (plyr_spr_1_scratchpad). Both floor axes are wanted: player_entry only sets
; the one he crossed, and the other is wherever he died.
entered_by:         DB      $FF
entered_at:         DW      0                   ; V, then U


; Put the player in the room that has just been built.
player_add:         ld      ix,player
                    ld      bc,PLAYER_U << 8 | PLAYER_V
                    ld      a,CHARACTER_Z
                    ld      hl,enter_dir
                    bit     7,(hl)              ; $FF: he did not walk in
                    jr      nz,.place
                    call    player_entry
.place:             ld      (entered_at),bc
                    call    character_add

                    ; Starting the room over, or the game: he comes in as a
                    ; sparkle. Drawn now rather than at the end of the turn, so
                    ; that the knight character_add has just drawn is not left
                    ; standing there for a turn first.
                    ld      a,(player_state)
                    cp      PLAYER_APPEARING
                    ret     nz
                    ld      ix,player
                    ld      a,PLAYER_APPEAR_GFX
                    call    player_sparkle
                    jp      redraw_flush


; Where the player stands when he walks into a room: two units inside the far
; wall, plus his own half, so his leading edge is already through the arch and
; he is standing in the opening. The axis he did not cross keeps its value,
; which is the middle of the room or near enough -- he had to be in the
; doorway to get out of the last one.
;
; His height comes from the arch itself, not from the floor. That is what
; carries him along the raised walkway of a tall room instead of dropping him
; into it, and it is what Knight Lore does too: adjust_plyr_Z_for_arch hunts
; down the arch he is entering by and takes its Z.
;
;   IX -> the player's legs
; Out: B - U, C - V, A - the Z to stand at. (enter_dir) is spent.
player_entry:       ld      a,(enter_dir)
                    ld      e,a
                    ld      c,a
                    ld      b,0
                    ld      hl,room_door_z
                    add     hl,bc
                    ld      a,(hl)
                    or      a
                    jr      nz,.height
                    ld      a,CHARACTER_Z       ; no arch that side: the floor
.height:            push    af

                    ld      b,(ix+OBJ.U)
                    ld      c,(ix+OBJ.V)
                    ld      hl,room_half_v      ; north and south cross V
                    bit     0,e
                    jr      z,.axis
                    ld      hl,room_half_u      ; east and west cross U
.axis:              ld      a,(hl)
                    sub     2
                    bit     1,e                 ; south and west are the near
                    jr      nz,.near            ; walls, north and east the far
                    add     a,128 + CHARACTER_HALF_U
                    jr      .store
.near:              neg
                    add     a,128 - CHARACTER_HALF_U
.store:             bit     0,e
                    jr      nz,.u
                    ld      c,a
                    jr      .done
.u:                 ld      b,a
.done:              ld      a,$FF
                    ld      (enter_dir),a
                    pop     af
                    ret


; Read the keys and walk the player.
;
; The four isometric directions are the two floor axes both ways, so the keys
; pair up as a diamond. Which facing each of them is comes from
; character_steps, and the numbers here are indexes into it.
KEY_UPLEFT          EQU     $FBFE       ; Q, bit 0
KEY_DOWNRIGHT       EQU     $FDFE       ; A, bit 0
KEY_RIGHT           EQU     $DFFE       ; P bit 0, O bit 1
KEY_JUMP            EQU     $7FFE       ; SPACE, bit 0

player_step:        ld      ix,player
                    ld      a,(player_state)
                    or      a
                    jp      nz,player_phase
                    ld      a,(player_touched)
                    or      a
                    jp      nz,player_die

                    ; Nobody else is walking about. object_collide tests this
                    ; on top of the room's pool, for the characters that are
                    ; not in it; there is one of those now, and it is him.
                    ld      hl,0
                    ld      (collide_other),hl

                    ; Whether he is standing in a doorway, worked out before
                    ; he moves and read twice after: character_collide lifts
                    ; the room's edge while it is set, and player_exit asks
                    ; whether the step took him right out.
                    call    character_door_find

                    ; The light has changed. He changes with it as soon as he
                    ; is standing on something -- chk_and_init_transform will not
                    ; start it in the air -- and is not waiting on the pot.
                    ld      a,(special_busy)
                    or      a
                    jr      nz,.busy
                    ld      a,(player_change)
                    or      a
                    jr      z,.keys
                    ld      a,(ix+CHARACTER_STATE)
                    or      (ix+CHARACTER_DZ)
                    jp      z,player_changing
                    jr      .keys

                    ; While something he dropped is on its way into the pot he
                    ; hangs where he is and nothing he presses counts. The game
                    ; gives him a dZ of two, which its gravity takes back to
                    ; nothing -- and ours takes two a turn off a knight who is
                    ; not holding jump, so the same number does the same.
.busy:              ld      (ix+CHARACTER_DZ),2
                    xor     a
                    ld      (character_jump_held),a
                    jp      character_stand

                    ; Picking up and putting down come first, as the game
                    ; has them.
.keys:              call    special_keys
                    ld      ix,player

                    ; The jump key first, because gravity asks about it in the
                    ; same turn: holding it is what makes the difference
                    ; between a hop and a full jump.
                    ld      bc,KEY_JUMP
                    in      a,(c)
                    rra                         ; a key reads 0 while it is held
                    ld      a,0
                    jr      c,.no_jump
                    inc     a
                    call    character_jump
.no_jump:           ld      (character_jump_held),a

                    ld      bc,KEY_UPLEFT
                    in      a,(c)
                    rra
                    jr      nc,.up_left
                    ld      bc,KEY_DOWNRIGHT
                    in      a,(c)
                    rra
                    jr      nc,.down_right
                    ld      bc,KEY_RIGHT
                    in      a,(c)
                    rra
                    jr      nc,.up_right
                    rra
                    jr      nc,.down_left

                    ; Nothing held. He still has to fall, and he is still
                    ; drawn, so that a turn costs about the same whether he
                    ; walks or not.
                    jp      character_stand

.up_left:           ld      a,0
                    jr      .walk
.up_right:          ld      a,1
                    jr      .walk
.down_left:         ld      a,3
                    jr      .walk
.down_right:        ld      a,2
.walk:              call    character_walk
                    ld      ix,player               ; the repaint took IX

                    ;; NB: fall through into player_exit


; Has the step taken him right out through the doorway he was in? The test is
; Knight Lore's, at screen_west and its three neighbours ($CA9A): out when the
; whole of him has passed the wall, not when he touches it.
;
; The castle is sixteen rooms by sixteen, and the number is a row and a column
; in it: north is a row on, east a column, and east and west wrap inside the
; row rather than carrying into it. Every one of the 260 doorways in the data
; has a matching one in the room that arithmetic lands on, which is as good a
; proof of it as measuring the game would be.
;
;   IX -> the player's legs
player_exit:        ld      a,(ix+CHARACTER_DOOR)
                    inc     a
                    ret     z                       ; not in a doorway
                    dec     a
                    ld      c,a

                    ld      a,(ix+OBJ.V)            ; north and south cross V
                    ld      hl,room_half_v
                    bit     0,c
                    jr      z,.axis
                    ld      a,(ix+OBJ.U)            ; east and west cross U
                    ld      hl,room_half_u
.axis:              ld      b,(hl)
                    bit     1,c
                    jr      nz,.near

                    ; North and east: his trailing edge has to be past the
                    ; far wall.
                    sub     CHARACTER_HALF_U
                    ld      e,a
                    ld      a,b
                    add     a,127                   ; one below the bound, so
                    cp      e                       ; carry means he is past it
                    ret     nc
                    jr      .out

                    ; South and west: his leading edge below the near wall.
.near:              add     a,CHARACTER_HALF_U
                    ld      e,a
                    ld      a,128
                    sub     b                       ; the near bound
                    ld      d,a
                    ld      a,e
                    cp      d
                    ret     nc                      ; not below it yet

.out:               ld      a,(room_number)
                    bit     0,c
                    jr      nz,.column
                    bit     1,c
                    jr      nz,.south
                    add     a,$10                   ; north, a row on
                    jr      .go
.south:             sub     $10
                    jr      .go
.column:            ld      e,a
                    inc     a                       ; east
                    bit     1,c
                    jr      z,.wrap
                    dec     a
                    dec     a                       ; west
.wrap:              and     $0F
                    ld      d,a
                    ld      a,e
                    and     $F0
                    or      d
.go:                ld      (room_number),a

                    ; He comes in by the opposite wall of the new room.
                    ld      a,c
                    xor     2
                    ld      (enter_dir),a
                    ret


; He has touched something that kills. upd_player_bottom at $C82B turns both
; halves to the first sparkle, and init_death_sparkles makes him something
; nothing collides with, so that whatever killed him walks on through.
;   IX -> the player's legs
player_die:         ld      a,PLAYER_DYING
                    ld      (player_state),a
                    set     2,(ix+OBJ.FLAGS)    ; OBJ_PASSABLE
                    ld      a,PLAYER_DEATH_GFX
                    jr      player_sparkle


; A turn of dying or of coming back.
;   A  - player_state, IX -> the player's legs
player_phase:       cp      PLAYER_CHANGING
                    jr      z,player_change_turn
                    cp      PLAYER_DYING
                    jr      nz,.appearing
                    ld      a,(ix+OBJ.GFX)
                    cp      PLAYER_DEATH_GFX + 7
                    jr      z,.gone
                    inc     a                   ; upd_112_to_118_184: a frame a turn
                    jr      player_sparkle

                    ; The last sparkle has had its turn. lose_life: a life, and
                    ; the room built again around him in the doorway he came in
                    ; by -- or, with none left, a new game.
.gone:              ld      hl,player_lives
                    dec     (hl)
                    jp      m,start
                    ld      a,PLAYER_APPEARING
                    ld      (player_state),a
                    ld      a,(entered_by)      ; the arch, for his height
                    ld      (enter_dir),a
                    ld      bc,(entered_at)
                    ld      (ix+OBJ.U),b
                    ld      (ix+OBJ.V),c
                    xor     a                   ; and in the shape the light says,
                    ld      (player_change),a   ; with no change still owing
                    ld      a,(night)
                    add     a,PLAYER_LEGS_GFX
                    call    player_form
                    ld      a,(room_number)
                    cpl                         ; anything but the room it is
                    ld      (room_shown),a
                    ret

.appearing:         ld      a,(ix+OBJ.GFX)
                    cp      PLAYER_APPEAR_GFX + 7
                    jr      z,.back
                    ld      a,(move_tick)       ; upd_120_to_126: every other turn
                    rra
                    ret     c
                    ld      a,(ix+OBJ.GFX)
                    inc     a
                    jr      player_sparkle

                    ; upd_127: himself again, and whatever touched him while he
                    ; was arriving forgotten.
.back:              xor     a
                    ld      (player_state),a
                    ld      (player_touched),a
                    ld      (ix+OBJ.DU),a       ; nor anything that shoved him
                    ld      (ix+OBJ.DV),a
                    call    character_frame
                    jr      player_repaint

; Both halves to one graphic, repainted where they stand.
;   A  - the graphic, IX -> the player's legs
player_sparkle:     ld      (ix+OBJ.GFX),a
                    ld      (ix+CHARACTER_BODY+OBJ.GFX),a
player_repaint:     ld      de,0
                    ld      (ix+OBJ.DZ),0
                    jp      character_move


; A turn of changing, upd_92_to_95: something deadly still kills him, and every
; fourth turn he twinkles on, until the last twinkle turns him into the other one.
;   IX -> the player's legs
player_change_turn: ld      a,(player_touched)
                    or      a
                    jp      nz,player_die
                    ld      a,(move_tick)
                    and     3
                    ret     nz
                    ld      hl,player_change
                    dec     (hl)
                    jr      nz,player_twinkle
                    ld      a,(ix+CHARACTER_LEGS)
                    xor     PLAYER_WOLF
                    call    player_form
                    ld      a,(ix+OBJ.BUF_H)    ; his own rotation buffer back, if
                    or      a                   ; he was ever given one
                    jp      z,player_phase.back
                    res     3,(ix+OBJ.FLAGS)    ; OBJ_SHARED_SHIFT
                    jp      player_phase.back


; He starts to change: nothing on top, and the legs twinkling. The twinkles are
; up to 38 rows tall, taller than the buffer his legs rotate into, so they
; rotate at draw time for the few turns they are up.
;   IX -> the player's legs
player_changing:    ld      a,PLAYER_CHANGING
                    ld      (player_state),a
                    ld      a,PLAYER_CHANGE_TURNS
                    ld      (player_change),a
                    set     3,(ix+OBJ.FLAGS)    ; OBJ_SHARED_SHIFT
                    ld      (ix+CHARACTER_BODY+OBJ.GFX),PLAYER_HIDDEN_GFX

                    ;; NB: fall through into player_twinkle


; One of the four twinkles at random, never the one he already shows, turned
; the other way round each time -- rand_legs_sprite, at $C357.
;   IX -> the player's legs
player_twinkle:     call    mover_rand
                    and     3
                    add     a,PLAYER_CHANGE_GFX
                    cp      (ix+OBJ.GFX)
                    jr      nz,.other
                    xor     1
.other:             ld      (ix+OBJ.GFX),a
                    ld      a,(ix+OBJ.FLAGS)
                    xor     OBJ_FLIP_H
                    ld      (ix+OBJ.FLAGS),a
                    jr      player_repaint


; The clock's turn. It stops once the wizard has everything, as the game's does.
day_step:           ld      a,(move_tick)
                    and     SUN_TURNS - 1
                    ret     nz
                    ld      a,(special_count)
                    cp      SPECIAL_WANTED
                    ret     nc
                    ld      hl,sun_x
                    inc     (hl)
                    ld      a,(hl)
                    cp      SUN_SET
                    ret     nz

                    ; The light changes, and so should he.
                    ld      (hl),SUN_RISE
                    ld      a,1
                    ld      (player_change),a
                    ld      hl,night
                    ld      a,(hl)
                    xor     PLAYER_WOLF
                    ld      (hl),a
                    ret     nz                  ; nightfall

                    ; Dawn: inc_days, and at forty the end. There is no screen
                    ; for that yet, so it is the same new game losing the last
                    ; life is.
                    ld      hl,days
                    ld      a,(hl)
                    add     a,1                 ; INC leaves the half-carry DAA wants
                    daa
                    ld      (hl),a
                    cp      DAYS_ALLOWED
                    ret     nz
                    jp      start


; The knight's two graphic bases, for man or wolf. character_frame works each
; frame out from them, so the wolf walks and turns with the knight's own code.
;   A - the legs' base: PLAYER_LEGS_GFX, plus PLAYER_WOLF for the wolf
player_form:        ld      (player + CHARACTER_LEGS),a
                    add     a,PLAYER_BODY_GFX - PLAYER_LEGS_GFX
                    ld      (player + CHARACTER_BODY_G),a
                    ret



; --- redrawing ------------------------------------------------------
;
; Nothing draws the whole screen. Each moving object repaints only the
; area it disturbed -- the union of where it was and where it now is --
; and objects_draw_all composites every object that intersects that area,
; so whatever it passed over is put back in the same pass.
;
; An area is bounded by what the view buffer holds: VIEW_BUF_WIDTH bytes
; across and VIEW_BUF_ROWS rows down, which is 8 x 64. A one-pixel step
; widens an object's extent by at most one byte -- a byte-aligned sprite
; spans w bytes and a shifted one w+1, and the union of two adjacent
; positions is never more than w+1 -- so with the widest sprite at 5 bytes
; the union peaks at 6 columns, and the tallest at 64 rows. Both fit.

region_rows:		DB		0
region_width:		DB		0


; redraw_orient used to live here: one pass per region, settling every
; shared graphic before objects_draw_all ran. That is one decision too few
; -- two objects in a region wanting opposite orientations leave whichever
; the pass reached last holding the graphic. sprite_orient asks per object
; instead, at the point of drawing, so this is gone.


; Start a region that several objects will be folded into. The bounds begin
; impossible -- a minimum nothing can be above, a maximum nothing can be below
; -- so the first region_add sets both. Adding nothing at all leaves them that
; way, which redraw_view would read as a region and try to draw, so every
; region_reset must be followed by at least one region_add.
region_reset:       ld      hl,$00FF            ; l = min, h = max
                    ld      (view_y_extent),hl
                    ld      (view_x_extent),hl
                    ret


; Widen the pending region to take in one object's extent.
;   IX -> the object
; Corrupts A and HL. DE, BC and IX are untouched, so a caller can hold a step
; in DE across it.
region_add:         ld      hl,view_y_extent
                    ld      a,(ix+OBJ.MIN_Y)
                    cp      (hl)
                    jr      nc,.max_y           ; keep whichever is smaller
                    ld      (hl),a
.max_y:             inc     hl
                    ld      a,(ix+OBJ.MAX_Y)
                    cp      (hl)
                    jr      c,.min_x            ; keep whichever is larger
                    ld      (hl),a
.min_x:             ld      hl,view_x_extent
                    ld      a,(ix+OBJ.MIN_X)
                    cp      (hl)
                    jr      nc,.max_x
                    ld      (hl),a
.max_x:             inc     hl
                    ld      a,(ix+OBJ.MAX_X)
                    cp      (hl)
                    ret     c
                    ld      (hl),a
                    ret


; A region that is waiting to be drawn, or a max of zero for none.
pend_y_extent:		dw		0
pend_x_extent:		dw		0


; Repaint a region -- but not yet, if it overlaps one already waiting.
;
; A ghost carrying two blocks is three movers, and each repainted its own area
; in turn: the ghost drew the stack, then each block drew very nearly the same
; patch again, walls behind it and all. Room $BB spent more than half its turn
; on the two repaints that changed nothing the first had not already drawn.
; Knight Lore never has the problem because it composes everything that moved
; into one frame.
;
; So a region joins the one waiting when the two overlap and the union still
; fits the view buffer, and otherwise the waiting one is drawn and this one
; waits in its place. Nothing is drawn wrong by waiting: a draw composites the
; objects as they are when it happens, never as they were when the region was
; made -- so a region drawn late shows the same thing a region drawn at once
; would, plus whatever has moved since. It is only ever a question of how many
; times the same pixels are drawn. redraw_flush draws what is left at the end
; of the turn.
;
; Regions that do not overlap are not merged even when they would fit: the
; rows between them would be composited for nothing.
;   view_y_extent, view_x_extent - the region
; Corrupts AF, BC, DE, HL; and IX, when it draws.
redraw_defer:		ld		a,(pend_y_extent+1)
					or		a
					jr		z,.adopt		; nothing waiting

					ld		hl,(view_y_extent)		; l = min, h = max
					ld		de,(pend_y_extent)		; e = min, d = max
					ld		a,l
					cp		d
					jr		nc,.apart		; starts below the waiting one's end
					ld		a,e
					cp		h
					jr		nc,.apart		; ...or ends above its start
					ld		a,e
					cp		l
					jr		c,.y_min
					ld		e,l
.y_min:				ld		a,d
					cp		h
					jr		nc,.y_max
					ld		d,h
.y_max:				ld		a,d
					sub		e
					cp		VIEW_BUF_ROWS + 1
					jr		nc,.apart		; together too tall for the buffer
					ld		b,d
					ld		c,e		; the union in Y, for if X agrees

					ld		hl,(view_x_extent)
					ld		de,(pend_x_extent)
					ld		a,l
					cp		d
					jr		nc,.apart
					ld		a,e
					cp		h
					jr		nc,.apart
					ld		a,e
					cp		l
					jr		c,.x_min
					ld		e,l
.x_min:				ld		a,d
					cp		h
					jr		nc,.x_max
					ld		d,h
.x_max:				ld		a,d
					sub		e
					cp		VIEW_BUF_WIDTH + 1
					jr		nc,.apart		; together too wide
					ld		(pend_x_extent),de
					ld		(pend_y_extent),bc
					ret

					; Draw the one waiting, and this one waits instead.
.apart:				ld		hl,(view_y_extent)
					ld		de,(pend_y_extent)
					ld		(pend_y_extent),hl
					ld		(view_y_extent),de
					ld		hl,(view_x_extent)
					ld		de,(pend_x_extent)
					ld		(pend_x_extent),hl
					ld		(view_x_extent),de
					jp		redraw_view

.adopt:				ld		hl,(view_y_extent)
					ld		(pend_y_extent),hl
					ld		hl,(view_x_extent)
					ld		(pend_x_extent),hl
					ret


; Draw the region still waiting, if there is one.
; Corrupts everything.
redraw_flush:		ld		a,(pend_y_extent+1)
					or		a
					ret		z
					ld		hl,(pend_y_extent)
					ld		(view_y_extent),hl
					ld		hl,(pend_x_extent)
					ld		(view_x_extent),hl
					ld		hl,0
					ld		(pend_y_extent),hl
					jp		redraw_view


; Repaint one object's own area, with no previous position to take in --
; what the opening screen is built from.
;   IX -> the object
redraw_object:		ld		a,(ix+OBJ.MIN_Y)
					ld		(view_y_extent),a
					ld		a,(ix+OBJ.MAX_Y)
					ld		(view_y_extent+1),a
					ld		a,(ix+OBJ.MIN_X)
					ld		(view_x_extent),a
					ld		a,(ix+OBJ.MAX_X)
					ld		(view_x_extent+1),a


; Clear the view buffer, composite everything that intersects the view
; extent into it, and copy the result to its place on the screen. Both
; extents are (min, max) with max exclusive, so max - min is a size.
; No object in the sprite set is taller than VIEW_BUF_ROWS, so there is no
; height case to handle here: the tallest is the 64-row castle arch and the
; buffer holds exactly 64. That is the whole reason the buffer went to
; 8 x 64 -- a region that does not fit has nowhere to go but wrap.
redraw_view:		ld		hl,(view_y_extent)	; l = min, h = max
					ld		a,h
					sub		l
					ret		z		; nothing to draw -- and the copy's
					; DJNZ would take a zero as 256 rows
					cp		VIEW_BUF_ROWS + 1		; taller than the buffer holds cannot
					ret		nc		; be drawn, and must not be tried:
					; the row address has one carry bit and
					; would land outside the buffer
					ld		(region_rows),a

					ld		hl,(view_x_extent)
					ld		a,h
					sub		l
					cp		VIEW_BUF_WIDTH + 1		; a region wider than the buffer has
					jr		c,.width_ok		; no routine to copy it, so clamp
					ld		a,VIEW_BUF_WIDTH		; rather than index off the end of
.width_ok:			ld		(region_width),a		; copy_routines
					ld		a,TURN_PER_REGION
					call	turn_add

					; Clear the rows this region uses, by pushing zeroes down through
					; them. PUSH writes two bytes for 11T against LDIR's 21T per byte,
					; so even blanking the lot this way beats LDIR over one region.
					;
					; It no longer blanks the lot, though. At 512 bytes that would be
					; 2816T every region, twice what the old 256-byte buffer cost, and
					; the rows past the region are never read. `push de` is one byte, so
					; where the run is entered decides how much it clears: rows * 8
					; bytes is rows * 4 pushes, so enter that many pushes from the end.
					; A 30-row region now costs 1320T, under what the flat clear cost.
					ld		(.restore_sp+1),sp		; save the real stack
					ld		a,(region_rows)
					ld		l,a
					ld		h,0
					add		hl,hl
					add		hl,hl		; hl = rows * 4, the pushes needed
					ld		e,l
					ld		d,h
					add		hl,hl		; hl = rows * 8, the bytes they cover
					ld		bc,view_buffer
					add		hl,bc
					ld		sp,hl		; PUSH pre-decrements, so this fills downwards
					ld		hl,.clear_end
					or		a
					sbc		hl,de		; ...from here, so exactly de pushes are left
					ld		de,0		; and this is what every one of them writes
					jp		(hl)
				REPT	VIEW_BUF_ROWS * VIEW_BUF_WIDTH / 2
					push	de
				ENDR
.clear_end:
.restore_sp:		ld		sp,0		; operand set just above

					; No orientation pass here any more. It settled the shared
					; graphics once for the whole region, which is one decision
					; too few: objects_draw_all now asks per object, in
					; sprite_orient, at the point it is about to draw one.
					call	objects_draw_all

					; Set the copy routine up for this width. There is one
					; of it: how many bytes of a row to move, and the step from
					; the end of one row of the buffer to the start of the
					; next, both go in as immediates.
					ld		a,(region_width)
					ld		b,a		; B is not wanted until pixelAddress
					ld		a,VIEW_BUF_WIDTH
					sub		b
					ld		(vid_buff_copy.hstride+1),a
					add		a		; the LDI chain is two bytes a column
					ld		(vid_buff_copy.entry+1),a

					; ...and where on the screen it goes
					ld		a,(view_x_extent)		; min x, in bytes
					add		a
					add		a
					add		a		; -> pixels
					ld		c,a
					ld		a,(view_y_extent)
					ld		b,a
					call	pixelAddress		; hl = screen address; bc kept
					ex		de,hl		; de = destination
					ld		hl,view_buffer
					ld		a,(region_rows)
					ld		b,a		; row counter, for the DJNZ. C is the copy
					; routine's own -- it resets it per row so
					; that LDI's countdown can never borrow
					; into B and lose a row.
					call	vid_buff_copy

					; The carried objects live in the bottom-left corner, straight on
					; the screen, and a region that reached them has just wiped them.
					ld		a,(view_y_extent+1)		; max, exclusive
					cp		SCREEN_ROWS - 24 + 1
					ret		c
					ld		a,(view_x_extent)
					cp		11		; their last column, plus one
					ret		nc
					ld		a,(view_x_extent+1)
					cp		3		; their first, plus one
					ret		c
					jp		special_show






; This is the final optimized code. It takes the X coordinate in the C register,
; and the Y coordinate in the B register. The screen address is returned in the HL register pair.
; BC and DE are unchanged, so there is no need for expensive push and pop operations.
pixelAddress:   ld      a, b
                and     %00000111
                ld      h, a    ; h contains Y2-Y0
                ld      a, b
                rra
                scf             ; set bit 14
                rra
                rra
                ld      l, a    ; l contains Y5-Y3
                and     %01011000
                or      h
                ld      h, a    ; h is complete now
                ld      a, c    ; divide X by 8
                rr      l       ; and rotate Y5-Y3 in
                rra
                rr      l
                rra
                rr      l
                rra
                ld      l, a    ; l is complete now
                ret



					INCLUDE "vid_buff.s"



; The stack grows down from the top of memory, so the image has to stop short of
; what it reserves there. This is the check that was missing when the player
; pushed the top of the image into the stack.
image_end:
                    ASSERT  $ <= $10000 - STACK_RESERVE
                    DISPLAY "code and data   $8000..", /H, image_end, "   free below the stack: ", /D, $10000 - STACK_RESERVE - image_end

; ---------------------------------------------------------------------------
; Building a room, down where the ROM keeps its system variables.
;
; $5B00 to $5FFF is the printer buffer and the system variables, and none of it
; is wanted: interrupts are off for good, nothing here calls the ROM, and the
; stack is up at STACK_TOP. room_wipe stops at $57FF and room_paper at $5AFF,
; so nothing the engine does reaches it either. Knight Lore makes the same
; judgement and parks its object table at $5C08.
;
; It is contended memory, so what goes here has to be code that does not run
; every turn -- and building a room is the definition of that. It happens once,
; when the room changes, and everything else in the file is untouched by it.
; The few bytes of it that ARE read every turn are room_half_u, room_floor_z
; and the door table, which is a handful of loads.
                    ORG     $5B00
                    INCLUDE "room.s"
room_code_end:
                    ASSERT  room_code_end <= $6000
                    DISPLAY "room builder     $5B00..", /H, room_code_end, "   free: ", /D, $6000 - room_code_end


; ---------------------------------------------------------------------------
; Two reservations, put where there is room for them.
;
; The room data ends well short of $8000 and nothing uses what is left, so the
; view buffer and the object pool go there rather than on the end of the image.
; They were on the end until the player arrived and pushed it past $FF00, where
; the stack would have pushed straight into the code -- and nothing would have
; said so, because an image that overruns the stack still assembles.
;
; The view buffer is aligned to its own size, so a row start is a multiple of
; the stride in both pages and `high view_buffer` is even -- the row address
; folds its top bit into D with a single `rl d`, which needs an even base.
                    ORG     $7400
                    ALIGN   512
view_buffer:        DS      VIEW_BUF_ROWS * VIEW_BUF_WIDTH

; The object pool. A room owns all of it: room_build refills it from the start,
; so nothing survives a room change. ROOM_MAX_OBJECTS is the fullest room in
; the castle, which rooms.py works out while generating room_data.s.
                    ALIGN   32
room_objects:
                REPT    ROOM_MAX_OBJECTS + SPECIAL_SLOTS
                    ALIGN   32
                    object_record   0,      0,              0, 0, 0
                ENDR

; Two tables that were up in the code region until it ran out of room. Neither
; is touched by anything that cares about contention -- bit_reverse_table only
; while a graphic is being mirrored, which happens when a room is built, and
; sprite_table once per object placed -- and both want an alignment that there
; is room to honour here and was not up there.
;
; sprite_table is read as `ld h,(high sprite_table)/2 / ld l,a / add hl,hl`, so
; its page has to be even: a 512 boundary, not merely a 256 one.
                    ALIGN   256
; Every byte with its bits the other way round, for mirroring a sprite. Knight
; Lore keeps the same table at $F100 and reaches it exactly this way, with the
; page in B and the byte in C.
bit_reverse_table:
                    bit_reverse_bytes

                    ALIGN   512
                    INCLUDE "sprite_table.s"

; And code that only runs when a key is pressed, in what is left.
                    INCLUDE "pickup.s"
pool_end:
                    ASSERT  $ <= $8000      ; still inside the gap
                    DISPLAY "buffer and pool $7400..", /H, pool_end, "   free: ", /D, $8000 - pool_end

