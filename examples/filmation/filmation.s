; Interrupts stay off for good. Every part of the drawing path repurposes
; SP as a data pointer -- object_update walks sprite data with it,
; objects_draw_all reads object records with it, the blitters read their
; sprites with it, and redraw_view clears the view buffer by pushing
; through it. An interrupt taken during any of those would push a return
; address into whatever SP was aimed at.
start:              di
                    ld      sp,STACK_TOP        ; off the contended stack, first thing

                    ; A game from the beginning -- which is also where losing the
                    ; last life comes back to.
                    ld      a,r                 ; init_start_location: one of four
                    and     3
                    ld      e,a
                    ld      d,0
                    ld      hl,start_rooms
                    add     hl,de
                    ld      a,(hl)
                    ld      (room_number),a
                    ld      a,$FF
                    ld      (enter_dir),a
                    ld      (entered_by),a
                    ld      a,PLAYER_LIVES
                    ld      (player_lives),a
                    ld      a,PLAYER_APPEARING
                    ld      (player_state),a
                    xor     a
                    ld      (player_touched),a
                    ld      (days),a
                    ld      (night),a
                    ld      (player_change),a
                    ld      a,SUN_RISE
                    ld      (sun_x),a
                    ld      a,PLAYER_LEGS_GFX
                    call    player_form
                    call    special_init

        ; Nothing goes into a room that was not built. room_build leaves the
        ; old room up when it is handed a number no record carries,
        ; and the old room's objects are still in the list -- so adding the
        ; characters again would insert records that are already there, and
        ; an object compared against itself ties, which makes the scan take
        ; itself as its own insertion point and link its NEXT to itself.
.enter:             call    special_room_leave
                    ld      a,(room_number)
                    call    room_build
                    jr      c,.entered
                    ld      a,(room_shown)      ; stay where we are
                    ld      (room_number),a
                    ld      a,$FF
                    ld      (enter_dir),a       ; and nobody walking in
                    jr      .loop
.entered:           ld      a,(room_number)
                    ld      (room_shown),a
                    ld      a,(enter_dir)       ; kept for starting the room over
                    ld      (entered_by),a
                    call    special_room_enter
                    call    player_add

                    ; Poke room_number from the debugger and the castle turns
                    ; over. The 1 and 2 keys do it from the keyboard.
.loop:              ld      a,(room_number)
                    ld      hl,room_shown
                    cp      (hl)
                    jr      nz,.enter

                    ; Nothing waits for the frame. There used to be an
                    ; `ei; halt; di` here, and it cost more than it bought: the
                    ; drawing takes longer than a frame, so the HALT found the
                    ; interrupt already gone and sat out a whole second one --
                    ; the loop ran at 25Hz to stay in step with a raster it was
                    ; never going to keep up with anyway. Knight Lore does not
                    ; wait either.
                    ;
                    ; Interrupts stay off, then, as they are everywhere else in
                    ; the engine: every part of the drawing path repurposes SP,
                    ; so one taken mid-blit would push a return address into a
                    ; sprite. Nothing needs them -- the keyboard is read
                    ; directly, in player_step, rather than through the ROM's
                    ; scan.
                    call    special_step
                    call    movers_step
                    call    player_step
                    call    day_step
                    call    redraw_flush        ; whatever the turn left waiting
                    call    print_room
                    call    room_keys
                    call    turn_pace
                    jr      .loop


; ---------------------------------------------------------------------------
; Keep the nearly empty rooms from racing.
;
; A turn takes as long as its work, and a room with nothing moving in it has
; almost none: a hundred turns a second, against twenty or thirty in a busy
; one. Knight Lore holds every frame to a fixed budget, counting interrupts in
; game_delay; we cannot count interrupts, because every part of the drawing
; path borrows SP and a single interrupt taken there would write into a sprite.
;
; So the turn counts its own work instead, as it goes, in units of about
; TURN_UNIT_T T-states, and whatever is left of TURN_BUDGET_T at the end is
; spent in a delay loop. A turn already over the budget pays nothing, so the
; busy rooms go exactly as fast as they did.
;
; The counts come from measuring: 258 turns across 43 rooms, timed by the
; emulator and fitted against what each did. A turn costs about 5,400 T to
; begin with, 172 for every row a blit composites and 1,300 for the blit itself,
; 3,900 for every region drawn, 15,000 for every collision gather, and 620 for
; every row rotated. Rounded into units, that predicts a turn to within 4,000 T
; for half of them and 10,000 T for nine in ten -- near enough, when the only
; question is how much of the gap to fill.
;
; It errs a little low, though -- a real turn runs some thousands of T past its
; count -- so the budget is set below the pace it is meant to give. Measured
; turn by turn across all 128 rooms: the 60 that ran faster than 45 turns a
; second now run at 33 to 38, median 35; a room already slower than about 30 is
; untouched; and a turn over the budget is never padded. What it costs is a
; little in the rooms just under the cap whose turns vary, where the light ones
; are padded and the heavy ones are not -- $09 and $12 lose about four and
; seven turns a second.
TURN_BUDGET_T       EQU     86000               ; about 35 turns a second
TURN_UNIT_T         EQU     172
TURN_BASE_T         EQU     5400
TURN_PER_BLIT       EQU     8                   ; plus a unit a row
TURN_PER_REGION     EQU     23
TURN_PER_GATHER     EQU     87
TURN_SPIN           EQU     11                  ; DJNZs making up one unit

turn_work:          DW      0

; Add A units to the turn's work. Corrupts AF and HL.
turn_add:           ld      hl,turn_work
                    add     a,(hl)
                    ld      (hl),a
                    ret     nc
                    inc     hl
                    inc     (hl)
                    ret


; Spend what is left of the budget, and start the next turn's count.
; One pass of .wait is 7 + (TURN_SPIN * 13 - 5) + 26 = 171 T, which is the unit.
turn_pace:          ld      hl,(TURN_BUDGET_T - TURN_BASE_T) / TURN_UNIT_T
                    ld      de,(turn_work)
                    or      a
                    sbc     hl,de
                    ld      de,0
                    ld      (turn_work),de
                    ret     c                   ; over the budget already
                    ret     z
.wait:              ld      b,TURN_SPIN
.spin:              djnz    .spin
                    dec     hl
                    ld      a,h
                    or      l
                    jr      nz,.wait
                    ret


; 1 goes back a room, 2 on to the next.
;
; Most numbers between one room and the next have no room against them, so
; this steps over them rather than making you press the key twenty times: it
; asks room_find for each number in turn. A room always finds itself again if
; there is nothing else, so the walk cannot run away.
;
; room_find is itself a walk now, so an unlucky press can cost a few thousand
; T-states. It is a key press, and it only ever happens between rooms.
;
; One room a press, not one a frame -- the whole row is compared against what
; it read last time, so holding the key down does nothing after the first.
KEY_ROOMS           EQU     $F7FE       ; 1 bit 0, 2 bit 1

room_keys:          ld      bc,KEY_ROOMS
                    in      a,(c)
                    cpl                         ; a key reads 0 while it is held
                    and     3
                    ld      hl,room_key_held
                    cp      (hl)
                    ld      (hl),a              ; LD does not touch the flags
                    ret     z                   ; nothing has changed
                    and     a
                    ret     z                   ; ...and nothing is held now
                    rra
                    ld      e,-1                ; 1: back a room
                    jr      c,.step
                    ld      e,1                 ; 2: on to the next
.step:              ld      a,(room_number)
.try:               add     a,e
                    ld      c,a
                    push    de
                    push    bc
                    call    room_find
                    pop     bc
                    pop     de
                    ld      a,c                 ; the number we tried
                    jr      nc,.try             ; no room there: keep going
                    ld      (room_number),a
                    ret

room_key_held:      DB      0


; Which room to build, and the one on the screen. A game begins in one of four,
; chosen at random -- Knight Lore's start_locations at $D1E2.
start_rooms:        DB      $2F, $44, $B3, $8F
room_number:        DB      $B3
room_shown:         DB      $B3

; Which side of the room being built the player is walking in through, or $FF
; for a room he did not walk into. player_entry spends it and puts it back.
enter_dir:          DB      $FF


; --- the player -------------------------------------------------------------
;
; A character like any other -- see character.s. The knight's legs are the
