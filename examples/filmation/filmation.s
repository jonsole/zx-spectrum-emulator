; The view buffer and the object pool used to sit here, at the top of the
; image. They are reserved at the foot of this file instead, in the gap between
; the room data and the code -- see there for why.

; The stride between records, which the pool's ALIGN fixes.
ROOM_STRIDE         EQU     32


; Interrupts stay off for good. Every part of the drawing path repurposes
; SP as a data pointer -- object_update walks sprite data with it,
; objects_draw_all reads object records with it, the blitters read their
; sprites with it, and redraw_view clears the view buffer by pushing
; through it. An interrupt taken during any of those would push a return
; address into whatever SP was aimed at.
start:              di
                    ld      sp,STACK_TOP        ; off the contended stack, first thing

        ; Nothing goes into a room that was not built. room_build leaves the
        ; old room up when it is handed a number no record carries,
        ; and the old room's objects are still in the list -- so adding the
        ; characters again would insert records that are already there, and
        ; an object compared against itself ties, which makes the scan take
        ; itself as its own insertion point and link its NEXT to itself.
.enter:             ld      a,(room_number)
                    call    room_build
                    jr      c,.entered
                    ld      a,(room_shown)      ; stay where we are
                    ld      (room_number),a
                    ld      a,$FF
                    ld      (enter_dir),a       ; and nobody walking in
                    jr      .loop
.entered:           ld      a,(room_number)
                    ld      (room_shown),a
                    call    wolf_add
                    call    player_add

                    ; Poke room_number from the debugger and the castle turns
                    ; over; otherwise the soldier just keeps walking.
.loop:              ld      a,(room_number)
                    ld      hl,room_shown
                    cp      (hl)
                    jr      nz,.enter

                    ; Nothing waits for the frame. There used to be an
                    ; `ei; halt; di` here, and it cost more than it bought: the
                    ; drawing takes longer than a frame, so the HALT found the
                    ; interrupt already gone and sat out a whole second one --
                    ; the loop ran at 25Hz to stay in step with a raster it was
                    ; never going to keep up with anyway. Knight Lore does not
                    ; wait either.
                    ;
                    ; Interrupts stay off, then, as they are everywhere else in
                    ; the engine: every part of the drawing path repurposes SP,
                    ; so one taken mid-blit would push a return address into a
                    ; sprite. Nothing needs them -- the keyboard is read
                    ; directly, in player_step, rather than through the ROM's
                    ; scan.
                    call    wolf_step
                    call    player_step
                    call    room_keys
                    jr      .loop


; 1 goes back a room, 2 on to the next.
;
; Most numbers between one room and the next have no room against them, so
; this steps over them rather than making you press the key twenty times: it
; asks room_find for each number in turn. A room always finds itself again if
; there is nothing else, so the walk cannot run away.
;
; room_find is itself a walk now, so an unlucky press can cost a few thousand
; T-states. It is a key press, and it only ever happens between rooms.
;
; One room a press, not one a frame -- the whole row is compared against what
; it read last time, so holding the key down does nothing after the first.
KEY_ROOMS           EQU     $F7FE       ; 1 bit 0, 2 bit 1

room_keys:          ld      bc,KEY_ROOMS
                    in      a,(c)
                    cpl                         ; a key reads 0 while it is held
                    and     3
                    ld      hl,room_key_held
                    cp      (hl)
                    ld      (hl),a              ; LD does not touch the flags
                    ret     z                   ; nothing has changed
                    and     a
                    ret     z                   ; ...and nothing is held now
                    rra
                    ld      e,-1                ; 1: back a room
                    jr      c,.step
                    ld      e,1                 ; 2: on to the next
.step:              ld      a,(room_number)
.try:               add     a,e
                    ld      c,a
                    push    de
                    push    bc
                    call    room_find
                    pop     bc
                    pop     de
                    ld      a,c                 ; the number we tried
                    jr      nc,.try             ; no room there: keep going
                    ld      (room_number),a
                    ret

room_key_held:      DB      0


; Which room to build. $88 is the cauldron room; $B3 is where the game begins.
room_number:        DB      $88
room_shown:         DB      $88

; Which side of the room being built the player is walking in through, or $FF
; for a room he did not walk into. player_entry spends it and puts it back.
enter_dir:          DB      $FF


; --- the soldier -------------------------------------------------------------
;
; A second character, walking a square around the room. That is the thing a
; static scene cannot show: the depth sort, as it passes in front of some
; scenery and behind the rest, and the redraw, which repaints the union of
; where it was and where it is rather than the screen.
;
; It used to be a ball on a four-legged path, and it is a soldier now because
; there is nothing more to say: the same two records the player is built from
; with two numbers changed. He walks on the knight's own legs, which is how
; the castle does it -- the soldier and the wizard both stand on graphic 145,
; the shared leg block at 144 -- and the only thing that makes him a different
; sort of character is that his torso is one frame each way round rather than
; six.
;
; Only one of him, though. The player and a second character between them
; repaint two regions a frame and the frame no longer fits: the loop takes two
; of them per turn, so the demo runs at 25Hz. A third would cost another.
;
; Neither is part of the room. room_objects is sized to the fullest room in
; the castle, so there is no spare slot, and room_build refills it from the
; start anyway -- nothing in it survives a room change. These records join the
; sorted list once the room is built, and rejoin after the next one.
; The soldier: the player's own legs under a helmeted torso that does not
; animate. Legs 16 rather than the 144 the game gives him, because the two are
; the same four sprites under different numbers and only the numbers the knight
; wears have been harvested both ways round -- graphic 145's nudge is 16-21's
; to the pixel, so nothing is lost by using theirs.
;
; Swapping these two numbers is the whole of making it someone else:
;   48, 64 with walking_character   the werewolf
;   16, 158 with standing_character the wizard
WOLF_LEGS_GFX       EQU     16
WOLF_BODY_GFX       EQU     30
WOLF_LO             EQU     84          ; the square it walks, chosen to weave
WOLF_HI             EQU     172         ; through the ring of blocks
WOLF_FACING         EQU     0           ; -U, so it starts by walking up-left

wolf:               standing_character WOLF_LEGS_GFX, WOLF_BODY_GFX, WOLF_FACING


; Put the soldier into the room that has just been built.
wolf_add:           ld      ix,wolf
                    ld      (ix+CHARACTER_FACING),WOLF_FACING
                    ld      b,WOLF_HI
                    ld      c,WOLF_LO
                    ld      a,CHARACTER_Z
                    jp      character_add


; One step along the square. The facings run 0 to 3 in the order the sides of
; a square do, which is not a coincidence -- character_steps is laid out so
; that they do.
wolf_step:          ld      ix,wolf
                    ld      hl,player
                    ld      (collide_other),hl
                    xor     a
                    ld      (character_jump_held),a     ; it never jumps
                    ld      a,(ix+CHARACTER_FACING)
                    call    character_walk
                    ld      ix,wolf                 ; the repaint took IX

                    ; ...or when something stops it. It walks a fixed square
                    ; and the square runs through whatever the room happens to
                    ; stand in it, so without this it wedges against the first
                    ; block it meets and stays there for the life of the room.
                    ; Turning is the whole of its intelligence.
                    ld      a,(collide_hit)
                    and     COLLIDE_U | COLLIDE_V
                    jr      nz,.turn

                    ; A side ends when the coordinate IT moves reaches the far
                    ; wall. Testing both would turn twice in the corner it
                    ; starts in, where U and V are both against a bound. Even
                    ; facings walk along U and odd ones along V.
                    ld      a,(ix+CHARACTER_FACING)
                    bit     0,a
                    ld      a,(ix+OBJ.U)
                    jr      z,.at_edge
                    ld      a,(ix+OBJ.V)
                    ; Reached or passed, not landed on exactly. A step is
                    ; three units now and the square is 88 across, so it steps
                    ; over the corner rather than onto it.
.at_edge:           cp      WOLF_HI
                    jr      nc,.turn
                    cp      WOLF_LO + 1
                    ret     nc
.turn:              ld      a,(ix+CHARACTER_FACING)
                    inc     a
                    and     3
                    ld      (ix+CHARACTER_FACING),a
                    ret


; --- the player -------------------------------------------------------------
;
; A character like any other -- see character.s. The knight's legs are the
; block at 16 and his body the one at 32; he starts facing away from the
; viewer and up the screen.
PLAYER_LEGS_GFX     EQU     16
PLAYER_BODY_GFX     EQU     32
PLAYER_U            EQU     128
PLAYER_V            EQU     104         ; clear of the cauldron at 128,128
PLAYER_FACING       EQU     0           ; -U, up and left

player:             walking_character PLAYER_LEGS_GFX, PLAYER_BODY_GFX, PLAYER_FACING


; Put the player in the room that has just been built.
player_add:         ld      ix,player
                    ld      b,PLAYER_U
                    ld      c,PLAYER_V
                    ld      a,CHARACTER_Z
                    ld      hl,enter_dir
                    bit     7,(hl)              ; $FF: he did not walk in
                    jr      nz,.place
                    call    player_entry
.place:             jp      character_add


; Where the player stands when he walks into a room: two units inside the far
; wall, plus his own half, so his leading edge is already through the arch and
; he is standing in the opening. The axis he did not cross keeps its value,
; which is the middle of the room or near enough -- he had to be in the
; doorway to get out of the last one.
;
; His height comes from the arch itself, not from the floor. That is what
; carries him along the raised walkway of a tall room instead of dropping him
; into it, and it is what Knight Lore does too: adjust_plyr_Z_for_arch hunts
; down the arch he is entering by and takes its Z.
;
;   IX -> the player's legs
; Out: B - U, C - V, A - the Z to stand at. (enter_dir) is spent.
player_entry:       ld      a,(enter_dir)
                    ld      e,a
                    ld      c,a
                    ld      b,0
                    ld      hl,room_door_z
                    add     hl,bc
                    ld      a,(hl)
                    or      a
                    jr      nz,.height
                    ld      a,CHARACTER_Z       ; no arch that side: the floor
.height:            push    af

                    ld      b,(ix+OBJ.U)
                    ld      c,(ix+OBJ.V)
                    ld      hl,room_half_v      ; north and south cross V
                    bit     0,e
                    jr      z,.axis
                    ld      hl,room_half_u      ; east and west cross U
.axis:              ld      a,(hl)
                    sub     2
                    bit     1,e                 ; south and west are the near
                    jr      nz,.near            ; walls, north and east the far
                    add     a,128 + CHARACTER_HALF_U
                    jr      .store
.near:              neg
                    add     a,128 - CHARACTER_HALF_U
.store:             bit     0,e
                    jr      nz,.u
                    ld      c,a
                    jr      .done
.u:                 ld      b,a
.done:              ld      a,$FF
                    ld      (enter_dir),a
                    pop     af
                    ret


; Read the keys and walk the player.
;
; The four isometric directions are the two floor axes both ways, so the keys
; pair up as a diamond. Which facing each of them is comes from
; character_steps, and the numbers here are indexes into it.
KEY_UPLEFT          EQU     $FBFE       ; Q, bit 0
KEY_DOWNRIGHT       EQU     $FDFE       ; A, bit 0
KEY_RIGHT           EQU     $DFFE       ; P bit 0, O bit 1
KEY_JUMP            EQU     $7FFE       ; SPACE, bit 0

player_step:        ld      ix,player
                    ld      hl,wolf                 ; the one other thing that
                    ld      (collide_other),hl      ; is not in the room's pool

                    ; Whether he is standing in a doorway, worked out before
                    ; he moves and read twice after: character_collide lifts
                    ; the room's edge while it is set, and player_exit asks
                    ; whether the step took him right out.
                    call    character_door_find

                    ; The jump key first, because gravity asks about it in the
                    ; same turn: holding it is what makes the difference
                    ; between a hop and a full jump.
                    ld      bc,KEY_JUMP
                    in      a,(c)
                    rra                         ; a key reads 0 while it is held
                    ld      a,0
                    jr      c,.no_jump
                    inc     a
                    call    character_jump
.no_jump:           ld      (character_jump_held),a

                    ld      bc,KEY_UPLEFT
                    in      a,(c)
                    rra
                    jr      nc,.up_left
                    ld      bc,KEY_DOWNRIGHT
                    in      a,(c)
                    rra
                    jr      nc,.down_right
                    ld      bc,KEY_RIGHT
                    in      a,(c)
                    rra
                    jr      nc,.up_right
                    rra
                    jr      nc,.down_left

                    ; Nothing held. He still has to fall, so this cannot just
                    ; return the way it used to -- but standing on the floor
                    ; with nothing to do costs no repaint, because
                    ; character_stand gives up when every axis came to zero.
                    jp      character_stand

.up_left:           ld      a,0
                    jr      .walk
.up_right:          ld      a,1
                    jr      .walk
.down_left:         ld      a,3
                    jr      .walk
.down_right:        ld      a,2
.walk:              call    character_walk
                    ld      ix,player               ; the repaint took IX

                    ;; NB: fall through into player_exit


; Has the step taken him right out through the doorway he was in? The test is
; Knight Lore's, at screen_west and its three neighbours ($CA9A): out when the
; whole of him has passed the wall, not when he touches it.
;
; The castle is sixteen rooms by sixteen, and the number is a row and a column
; in it: north is a row on, east a column, and east and west wrap inside the
; row rather than carrying into it. Every one of the 260 doorways in the data
; has a matching one in the room that arithmetic lands on, which is as good a
; proof of it as measuring the game would be.
;
;   IX -> the player's legs
player_exit:        ld      a,(ix+CHARACTER_DOOR)
                    inc     a
                    ret     z                       ; not in a doorway
                    dec     a
                    ld      c,a

                    ld      a,(ix+OBJ.V)            ; north and south cross V
                    ld      hl,room_half_v
                    bit     0,c
                    jr      z,.axis
                    ld      a,(ix+OBJ.U)            ; east and west cross U
                    ld      hl,room_half_u
.axis:              ld      b,(hl)
                    bit     1,c
                    jr      nz,.near

                    ; North and east: his trailing edge has to be past the
                    ; far wall.
                    sub     CHARACTER_HALF_U
                    ld      e,a
                    ld      a,b
                    add     a,127                   ; one below the bound, so
                    cp      e                       ; carry means he is past it
                    ret     nc
                    jr      .out

                    ; South and west: his leading edge below the near wall.
.near:              add     a,CHARACTER_HALF_U
                    ld      e,a
                    ld      a,128
                    sub     b                       ; the near bound
                    ld      d,a
                    ld      a,e
                    cp      d
                    ret     nc                      ; not below it yet

.out:               ld      a,(room_number)
                    bit     0,c
                    jr      nz,.column
                    bit     1,c
                    jr      nz,.south
                    add     a,$10                   ; north, a row on
                    jr      .go
.south:             sub     $10
                    jr      .go
.column:            ld      e,a
                    inc     a                       ; east
                    bit     1,c
                    jr      z,.wrap
                    dec     a
                    dec     a                       ; west
.wrap:              and     $0F
                    ld      d,a
                    ld      a,e
                    and     $F0
                    or      d
.go:                ld      (room_number),a

                    ; He comes in by the opposite wall of the new room.
                    ld      a,c
                    xor     2
                    ld      (enter_dir),a
                    ret


; --- redrawing ------------------------------------------------------
;
; Nothing draws the whole screen. Each moving object repaints only the
; area it disturbed -- the union of where it was and where it now is --
; and objects_draw_all composites every object that intersects that area,
; so whatever it passed over is put back in the same pass.
;
; An area is bounded by what the view buffer holds: VIEW_BUF_WIDTH bytes
; across and VIEW_BUF_ROWS rows down, which is 8 x 64. A one-pixel step
; widens an object's extent by at most one byte -- a byte-aligned sprite
; spans w bytes and a shifted one w+1, and the union of two adjacent
; positions is never more than w+1 -- so with the widest sprite at 5 bytes
; the union peaks at 6 columns, and the tallest at 64 rows. Both fit.

region_rows:		DB		0
region_width:		DB		0


; ...and where it was in the world, which is what depth_relink gates on.
prev_u:				DB		0
prev_v:				DB		0
prev_z:				DB		0

; redraw_orient used to live here: one pass per region, settling every
; shared graphic before objects_draw_all ran. That is one decision too few
; -- two objects in a region wanting opposite orientations leave whichever
; the pass reached last holding the graphic. sprite_orient asks per object
; instead, at the point of drawing, so this is gone.


; Start a region that several objects will be folded into. The bounds begin
; impossible -- a minimum nothing can be above, a maximum nothing can be below
; -- so the first region_add sets both. Adding nothing at all leaves them that
; way, which redraw_view would read as a region and try to draw, so every
; region_reset must be followed by at least one region_add.
region_reset:       ld      hl,$00FF            ; l = min, h = max
                    ld      (view_y_extent),hl
                    ld      (view_x_extent),hl
                    ret


; Widen the pending region to take in one object's extent.
;   IX -> the object
; Corrupts A and HL. DE, BC and IX are untouched, so a caller can hold a step
; in DE across it.
region_add:         ld      hl,view_y_extent
                    ld      a,(ix+OBJ.MIN_Y)
                    cp      (hl)
                    jr      nc,.max_y           ; keep whichever is smaller
                    ld      (hl),a
.max_y:             inc     hl
                    ld      a,(ix+OBJ.MAX_Y)
                    cp      (hl)
                    jr      c,.min_x            ; keep whichever is larger
                    ld      (hl),a
.min_x:             ld      hl,view_x_extent
                    ld      a,(ix+OBJ.MIN_X)
                    cp      (hl)
                    jr      nc,.max_x
                    ld      (hl),a
.max_x:             inc     hl
                    ld      a,(ix+OBJ.MAX_X)
                    cp      (hl)
                    ret     c
                    ld      (hl),a
                    ret


; Remember where an object was, before it moves. Only depth_relink reads this,
; and only the world coordinates: the screen extents were saved here too, for a
; redraw that took in the old position as well as the new, and region_reset and
; region_add replaced that with an accumulated region.
;   IX -> the object
extent_save:		ld		a,(ix+OBJ.U)
					ld		(prev_u),a
					ld		a,(ix+OBJ.V)
					ld		(prev_v),a
					ld		a,(ix+OBJ.Z)
					ld		(prev_z),a
					ret		


; Repaint one object's own area, with no previous position to take in --
; what the opening screen is built from.
;   IX -> the object
redraw_object:		ld		a,(ix+OBJ.MIN_Y)
					ld		(view_y_extent),a
					ld		a,(ix+OBJ.MAX_Y)
					ld		(view_y_extent+1),a
					ld		a,(ix+OBJ.MIN_X)
					ld		(view_x_extent),a
					ld		a,(ix+OBJ.MAX_X)
					ld		(view_x_extent+1),a


; Clear the view buffer, composite everything that intersects the view
; extent into it, and copy the result to its place on the screen. Both
; extents are (min, max) with max exclusive, so max - min is a size.
; No object in the sprite set is taller than VIEW_BUF_ROWS, so there is no
; height case to handle here: the tallest is the 64-row castle arch and the
; buffer holds exactly 64. That is the whole reason the buffer went to
; 8 x 64 -- a region that does not fit has nowhere to go but wrap.
redraw_view:		ld		hl,(view_y_extent)	; l = min, h = max
					ld		a,h
					sub		l
					ret		z		; nothing to draw -- and the copy's
					; DJNZ would take a zero as 256 rows
					cp		VIEW_BUF_ROWS + 1		; taller than the buffer holds cannot
					ret		nc		; be drawn, and must not be tried:
					; the row address has one carry bit and
					; would land outside the buffer
					ld		(region_rows),a

					ld		hl,(view_x_extent)
					ld		a,h
					sub		l
					cp		VIEW_BUF_WIDTH + 1		; a region wider than the buffer has
					jr		c,.width_ok		; no routine to copy it, so clamp
					ld		a,VIEW_BUF_WIDTH		; rather than index off the end of
.width_ok:			ld		(region_width),a		; copy_routines

					; Clear the rows this region uses, by pushing zeroes down through
					; them. PUSH writes two bytes for 11T against LDIR's 21T per byte,
					; so even blanking the lot this way beats LDIR over one region.
					;
					; It no longer blanks the lot, though. At 512 bytes that would be
					; 2816T every region, twice what the old 256-byte buffer cost, and
					; the rows past the region are never read. `push de` is one byte, so
					; where the run is entered decides how much it clears: rows * 8
					; bytes is rows * 4 pushes, so enter that many pushes from the end.
					; A 30-row region now costs 1320T, under what the flat clear cost.
					ld		(.restore_sp+1),sp		; save the real stack
					ld		a,(region_rows)
					ld		l,a
					ld		h,0
					add		hl,hl
					add		hl,hl		; hl = rows * 4, the pushes needed
					ld		e,l
					ld		d,h
					add		hl,hl		; hl = rows * 8, the bytes they cover
					ld		bc,view_buffer
					add		hl,bc
					ld		sp,hl		; PUSH pre-decrements, so this fills downwards
					ld		hl,.clear_end
					or		a
					sbc		hl,de		; ...from here, so exactly de pushes are left
					ld		de,0		; and this is what every one of them writes
					jp		(hl)
				REPT	VIEW_BUF_ROWS * VIEW_BUF_WIDTH / 2
					push	de
				ENDR
.clear_end:
.restore_sp:		ld		sp,0		; operand set just above

					; No orientation pass here any more. It settled the shared
					; graphics once for the whole region, which is one decision
					; too few: objects_draw_all now asks per object, in
					; sprite_orient, at the point it is about to draw one.
					call	objects_draw_all

					; Set the copy routine up for this width. There is one
					; of it: how many bytes of a row to move, and the step from
					; the end of one row of the buffer to the start of the
					; next, both go in as immediates.
					ld		a,(region_width)
					ld		b,a		; B is not wanted until pixelAddress
					ld		a,VIEW_BUF_WIDTH
					sub		b
					ld		(vid_buff_copy.hstride+1),a
					add		a		; the LDI chain is two bytes a column
					ld		(vid_buff_copy.entry+1),a

					; ...and where on the screen it goes
					ld		a,(view_x_extent)		; min x, in bytes
					add		a
					add		a
					add		a		; -> pixels
					ld		c,a
					ld		a,(view_y_extent)
					ld		b,a
					call	pixelAddress		; hl = screen address; bc kept
					ex		de,hl		; de = destination
					ld		hl,view_buffer
					ld		a,(region_rows)
					ld		b,a		; row counter, for the DJNZ. C is the copy
					; routine's own -- it resets it per row so
					; that LDI's countdown can never borrow
					; into B and lose a row.
					call	vid_buff_copy
					ret		






; This is the final optimized code. It takes the X coordinate in the C register,
; and the Y coordinate in the B register. The screen address is returned in the HL register pair.
; BC and DE are unchanged, so there is no need for expensive push and pop operations.
pixelAddress:   ld      a, b
                and     %00000111
                ld      h, a    ; h contains Y2-Y0
                ld      a, b
                rra
                scf             ; set bit 14
                rra
                rra
                ld      l, a    ; l contains Y5-Y3
                and     %01011000
                or      h
                ld      h, a    ; h is complete now
                ld      a, c    ; divide X by 8
                rr      l       ; and rotate Y5-Y3 in
                rra
                rr      l
                rra
                rr      l
                rra
                ld      l, a    ; l is complete now
                ret



