"""Lookup tables for the road engine, generated at build time.

Every table is page aligned (256 entries, one page each, or a lo page and a
hi page for 16-bit values) so the Z80 indexes it with H = page, L = index.

xhi_lo/hi  The screen-x offset of a relative yaw angle's high byte (a signed
           yaw unit, 256 to a turn): yaw * 256 / 40, as a signed 16-bit value.
xfrac      The screen-x offset of the yaw angle's low byte: lo * 256 / 40 / 256.
mask       The bits of a screen byte from pixel x rightwards: $FF >> (x & 7),
           indexed by x itself so compose_screen needs no AND.
logft      256 * log2(distance / larger delta) for a ratio T = 256 * smaller /
           larger: GetObjectDistance's alpha max plus beta min (max + min / 8
           while the BBC's arctanY(T) is below 103, else max * 7/8 + min / 2),
           as a correction to the larger delta's log.
a32_lo/hi  32 * arctanY(T), the BBC's arctanY being INT(0.5 + ATN(T / 256) *
           256 / ATN(1)): the octant's angle as a 16-bit yaw (256 units to a
           turn in the high byte).

xhi_lo/xhi_hi/xfrac and logft/a32_lo/a32_hi are consecutive pages: the code
steps between them with INC H.

The screen maps the BBC's 40-unit field of view across 256 pixels, so x = 128
+ yaw / 40 for a 16-bit yaw angle.

Two bigger groups go elsewhere (see revs.s):

log12_lo/hi  256 * log2(i) for i = 1..4095, 4K each: log16 looks a 16-bit
             value up directly below 4096, or its top twelve bits above.
exp8         floor(2 ^ (n + f / 256)) for n = 0..7, f = 0..255: a page for
             each whole part n, so an antilogarithm below 256 is one lookup.
"""

import math

PAGES = {}


def table(name, values):
    assert len(values) == 256
    PAGES[name] = [v & 0xFF for v in values]


def arctan_y(t):
    return int(0.5 + math.atan(t / 256) * 256 / math.atan(1))


def build():
    xhi = [round((i - 256 if i >= 128 else i) * 256 / 40) for i in range(256)]
    table("xhi_lo", [v & 0xFF for v in xhi])
    table("xhi_hi", [(v >> 8) & 0xFF for v in xhi])
    table("xfrac", [int(i * 256 / 40 / 256) for i in range(256)])
    table("mask", [0xFF >> (i & 7) for i in range(256)])
    logft = []
    for t in range(256):
        r = t / 256
        f = 1 + r / 8 if arctan_y(t) < 103 else 7 / 8 + r / 2
        logft.append(round(256 * math.log2(f)))
    table("logft", logft)
    a32 = [32 * arctan_y(t) for t in range(256)]
    table("a32_lo", [v & 0xFF for v in a32])
    table("a32_hi", [v >> 8 for v in a32])


def big_tables():
    """The log12 and exp8 groups, as {name: bytes}."""
    logs = [0] + [round(256 * math.log2(i)) for i in range(1, 4096)]
    exp8 = []
    for n in range(8):
        exp8 += [min(255, int(2 ** (n + f / 256) + 1e-9)) for f in range(256)]
    return {"log12_lo": bytes(v & 0xFF for v in logs), "log12_hi": bytes(v >> 8 for v in logs),
            "exp8": bytes(exp8)}


def big_source(names):
    big = big_tables()
    out = ["; Generated by tables.py."]
    for name in names:
        out.append(f"tbl_{name}:")
        values = big[name]
        for i in range(0, len(values), 16):
            out.append("    db " + ",".join(f"${v:02X}" for v in values[i:i + 16]))
    return "\n".join(out) + "\n"


def source():
    build()
    out = ["; Generated by tables.py -- page-aligned lookup tables, one page each.",
           "    ALIGN 256"]
    for name, values in PAGES.items():
        out.append(f"tbl_{name}:")
        for i in range(0, 256, 16):
            out.append("    db " + ",".join(f"${v:02X}" for v in values[i:i + 16]))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    print(source()[:400])
