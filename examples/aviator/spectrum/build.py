"""Assembles the Spectrum version: sjasmplus, from spectrum/aviator.s to
output/aviator.{z80,sld,lst}.

Generated first, into output/ and never committed, since they hold
Acornsoft's data:

- gen_bbc_labels.s: every label of the original's data, as an EQU at its
  Spectrum address (layout.py: the BBC's address + $8000), so the Z80 code
  uses the original's names;
- gen_bbc_data.s: the data regions' starting contents, from the original's
  binary as its loader leaves it (model.game.load_image);
- gen_screen.bin: the screen the game starts with, the canopy's frame and
  the dashboard, as model/zx.py draws them;
- gen_overlay.s: the frame's parts inside the canopy buffer, which are laid
  over each view as it is copied to the screen.

sjasmplus writes all 48K of RAM with the SAVEBIN at the bottom of
aviator.s; this wraps it as a version 3 .z80 that starts at `start`.

    python spectrum/build.py [--define NAME ...]
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
REPO = ROOT.parent.parent
OUT = ROOT / "output"
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))

import layout  # noqa: E402
from model import game, memory, names, zx  # noqa: E402

SJASMPLUS_CANDIDATES = [REPO / "tools" / "sjasmplus" / "sjasmplus.exe"]


def find_sjasmplus():
    named = os.environ.get("SJASMPLUS")
    if named and Path(named).is_file():
        return named
    for candidate in SJASMPLUS_CANDIDATES:
        if candidate.is_file():
            return str(candidate)
    found = shutil.which("sjasmplus")
    if found:
        return found
    sys.exit("sjasmplus not found: put it in tools/sjasmplus or name it in SJASMPLUS")


def generate():
    OUT.mkdir(exist_ok=True)
    spans = layout.regions()
    labels = layout.labels(spans)
    lines = ["; The original's data labels at their Spectrum addresses (spectrum/layout.py).",
             "; Generated by spectrum/build.py from Acornsoft's listing; not committed."]
    for name, addr in sorted(labels.items(), key=lambda kv: (kv[1], kv[0])):
        lines.append(f"{name} equ ${addr:04X}")
    # The source's configuration constants that the Z80 code uses too.
    lines.append(f"nextAxis equ {names.nextAxis}")
    lines.append(f"BBC_OFFSET equ ${layout.OFFSET:04X}")
    (OUT / "gen_bbc_labels.s").write_text("\n".join(lines) + "\n")

    # The data starts as the game is when StartGame has run, on the
    # original's binary as its loader leaves it.
    game.wire_hooks()
    game.load_image()
    game.start_game()
    image = memory.M
    lines = ["; The data regions' starting contents: the original's binary as its loader",
             "; leaves it, after StartGame. Generated by spectrum/build.py; not committed."]
    for lo, hi in spans:
        lines.append(f"    ORG ${lo + layout.OFFSET:04X}")
        for i in range(lo, hi, 16):
            chunk = image[i:min(i + 16, hi)]
            lines.append("    db " + ",".join(f"${b:02X}" for b in chunk))
    (OUT / "gen_bbc_data.s").write_text("\n".join(lines) + "\n")

    # Quarter squares for mul8: n * n / 4 for n = 0 to 511, low bytes then
    # high bytes, two pages each.
    squares = [n * n // 4 for n in range(512)]
    lines = ["; Quarter squares, n * n / 4 for n = 0 to 511: low bytes (SQ_LO), then",
             "; high bytes (SQ_HI). Generated by spectrum/build.py."]
    for part in (0, 8):
        for i in range(0, 512, 16):
            lines.append("    db " + ",".join(f"${(s >> part) & 0xFF:02X}" for s in squares[i:i + 16]))
    (OUT / "gen_tables.s").write_text("\n".join(lines) + "\n")

    screen = zx.Screen()
    (OUT / "gen_screen.bin").write_bytes(screen.scr())
    (OUT / "gen_view.s").write_text(view_tables(screen))
    # The canopy buffer starts empty, and so do the extents of what this view
    # and the last drew in it (view.s): lo $FF and hi 0, 120 bytes apart,
    # this view's in one page and the last's in the next. The row after the
    # last is never empty, which ends present's search for rows to copy.
    (OUT / "gen_buffer.bin").write_bytes(bytes(32 * zx.CANOPY_ROWS))
    this = bytearray([0xFF] * 120 + [0] * 120 + [0] * 16)
    this[zx.CANOPY_ROWS] = 0
    extents = bytes(this) + bytes([0xFF] * 120 + [0] * 120)
    (OUT / "gen_extents.bin").write_bytes(extents)
    (OUT / "gen_flight.s").write_text(flight_table())


def _db(values):
    return ["    db " + ",".join(f"${v:02X}" for v in values[i:i + 16]) for i in range(0, len(values), 16)]


def view_tables(screen):
    """The view's tables, from view_x ($EC00) on: BBC x to Spectrum x, BBC
    canopy y to buffer row, the pixel masks, the screen address of each
    buffer row, and the frame's overlay -- which may only touch each row's
    first two and last two bytes, as present relies on it."""
    lines = ["; The canopy view's tables (spectrum/aviator.s has their addresses).",
             "; Generated by spectrum/build.py from model/zx.py."]
    lines += _db([zx.sx(x) if x < zx.BBC_WIDTH else 0 for x in range(256)])      # view_x
    lines += _db([zx.sy(zx.BBC_CANOPY_BOTTOM_ROW - y) - zx.CANOPY_TOP
                  if y <= 151 else 0 for y in range(256)])                         # view_y
    lines += _db([0x80 >> n for n in range(8)])                                    # bit_masks
    rows = []
    for row in range(zx.CANOPY_ROWS):
        a = 0x4000 + zx.address(0, zx.CANOPY_TOP + row)
        rows += [a & 0xFF, a >> 8]
    lines += _db(rows)                                                             # view_rows
    lines += _db([0] * (0x100 - 8 - len(rows)))                                    # up to the overlay
    overlay = []
    for row in range(zx.CANOPY_ROWS):
        base = row * 32
        for b in range(32):
            keep, add = screen.overlay_keep[base + b], screen.overlay_or[base + b]
            if (keep != 0xFF or add) and b not in (0, 1, 30, 31):
                sys.exit(f"overlay touches byte {b} of canopy row {row}")
        for b in (0, 1, 30, 31):
            overlay += [screen.overlay_keep[base + b], screen.overlay_or[base + b]]
    lines += _db(overlay)                                                          # canopy_overlay
    return "\n".join(lines) + "\n"


FLIGHT_FIRST, FLIGHT_COUNT = 600, 520
FLIGHT_CACHE = ROOT / "data" / "stage1_flight.v1.bin"
PLANE_STATE = ("xPlaneLo", "xPlaneHi", "xPlaneTop", "yPlaneLo", "yPlaneHi", "yPlaneTop",
               "zPlaneLo", "zPlaneHi", "zPlaneTop", "xRotationLo", "xRotationHi",
               "yRotationLo", "yRotationHi", "zRotationLo", "zRotationHi")


def recorded_flight():
    """The plane's position and rotation through iterations 600 to 1119 of
    the tour flight, as the Python port flies it, 15 bytes an iteration in
    PLANE_STATE's order. Cached in data/, since it is the game's own
    numbers."""
    if FLIGHT_CACHE.exists():
        return FLIGHT_CACHE.read_bytes()
    sys.path.insert(0, str(ROOT / "tests"))
    import recorder
    from model import hardware
    clock = [0]

    def tick():
        clock[0] += 3
        return clock[0]

    hardware.clock = tick
    keys, _ = recorder.FLIGHTS["tour"]
    ranges = recorder.parse_keys(keys)
    g = game.Game()
    out = bytearray()
    for i in range(FLIGHT_FIRST + FLIGHT_COUNT):
        held = [k for lo, hi, ks in ranges if lo <= i < hi for k in ks]
        codes = {hardware.KEY_CODES[k] for k in held}
        hardware.keys = lambda code: code in codes
        g.iterate()
        if i >= FLIGHT_FIRST:
            out += bytes(memory.M[getattr(names, name)] for name in PLANE_STATE)
    hardware.keys = hardware._no_keys
    hardware.clock = hardware._stopped_clock
    FLIGHT_CACHE.parent.mkdir(exist_ok=True)
    FLIGHT_CACHE.write_bytes(bytes(out))
    return bytes(out)


def flight_table():
    data = recorded_flight()
    lines = ["; The tour flight's iterations 600 to 1119 as the Python port flies them:",
             "; the plane's position and rotation, 15 bytes each, in place_plane's order.",
             "; Generated by spectrum/build.py; not committed.", "flight_table:"]
    for i in range(0, len(data), 15):
        lines.append("    db " + ",".join(f"${b:02X}" for b in data[i:i + 15]))
    lines.append("flight_table_end:")
    return "\n".join(lines) + "\n"


def assemble(sjasmplus, defines):
    subprocess.run([sjasmplus, "--nologo", f"--sld={(OUT / "aviator.sld").as_posix()}", "--fullpath",
                    f"--lst={(OUT / "aviator.lst").as_posix()}", f"-I{OUT.as_posix()}", f"-I{HERE.as_posix()}",
                    *[f"-D{d}" for d in defines], (HERE / "aviator.s").as_posix()],
                   cwd=ROOT, check=True)
    ram = (OUT / "aviator.bin").read_bytes()
    start = find_label(OUT / "aviator.sld", "start")
    (OUT / "aviator.z80").write_bytes(z80_snapshot(ram, start))
    print(f"Wrote {OUT / 'aviator.z80'} (PC ${start:04X})")


def find_label(sld, name):
    for line in sld.read_text(encoding="utf-8").splitlines():
        fields = line.split("|")
        if len(fields) >= 8 and fields[6] == "L":
            parts = fields[7].split(",")
            if len(parts) > 2 and parts[1] == name and parts[2] == "":
                return int(fields[5])
    sys.exit(f"no label {name} in {sld}")


# A version 3 .z80 of the 48K, as examples/revs/build.py writes one.
Z80_V3_EXTRA = 54
Z80_PAGES = ((8, 0x0000), (4, 0x4000), (5, 0x8000))


def z80_compress(data):
    out = bytearray()
    i = 0
    while i < len(data):
        b = data[i]
        run = 1
        while i + run < len(data) and data[i + run] == b and run < 255:
            run += 1
        if run >= 5 or (b == 0xED and run >= 2):
            out += bytes((0xED, 0xED, run, b))
            i += run
        elif b == 0xED:
            out += data[i:i + 2]
            i += 2
        else:
            out.append(b)
            i += 1
    return bytes(out)


def z80_snapshot(ram, pc):
    assert len(ram) == 0xC000, len(ram)
    header = bytearray(30 + 2 + Z80_V3_EXTRA)
    header[10] = 0x3F
    header[29] = 1
    header[30:32] = Z80_V3_EXTRA.to_bytes(2, "little")
    header[32:34] = pc.to_bytes(2, "little")
    header[61] = header[62] = 0xFF
    body = bytearray()
    for page, offset in Z80_PAGES:
        packed = z80_compress(ram[offset:offset + 0x4000])
        body += len(packed).to_bytes(2, "little") + bytes((page,)) + packed
    return bytes(header + body)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--define", action="append", default=[], metavar="NAME")
    args = ap.parse_args()
    generate()
    assemble(find_sjasmplus(), args.define)


if __name__ == "__main__":
    main()
