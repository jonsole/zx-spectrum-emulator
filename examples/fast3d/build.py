"""Builds fast3d: the tables, from model.py, into output/tables_gen.s; then
sjasmplus on demo.s, for output/demo.z80 (with its SLD), and on checks.s, the
routines alone at $8000, for output/checks.bin and .sld, which check.py runs.

    python build.py
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "output"
REPO = HERE.parent.parent
sys.path.insert(0, str(HERE))
import model                                                      # noqa: E402

sys.path.insert(0, str(HERE.parent / "filmation"))
import z80file                                                    # noqa: E402

SJASMPLUS = [REPO / "tools" / "sjasmplus" / "sjasmplus.exe",
             REPO / ".venv-win" / "Scripts" / "sjasmplus.exe"]


def find_sjasmplus() -> str:
    for candidate in SJASMPLUS:
        if candidate.is_file():
            return str(candidate)
    found = shutil.which("sjasmplus")
    if found:
        return found
    sys.exit("sjasmplus not found -- see examples/filmation/knightlore/build.py")


def find_label(sld: Path, name: str) -> int:
    """A label's address, from the SLD's label records."""
    for line in sld.read_text(encoding="utf-8").splitlines():
        fields = line.split("|")
        if len(fields) >= 8 and fields[6] == "L":
            parts = fields[7].split(",")
            if len(parts) > 2 and parts[1] == name and parts[2] == "":
                return int(fields[5])
    sys.exit(f"no label {name} in {sld}")


def data_lines(values: list[int]) -> list[str]:
    return ["\t\t\t\t\tDB\t\t" + ",".join(f"${v & 0xFF:02X}" for v in values[i:i + 16])
            for i in range(0, len(values), 16)]


def write_tables(path: Path) -> None:
    squares = [model.quarter_square(n) for n in range(-256, 256)]
    sines = [model.sine(a) & 0xFFFF for a in range(256)]
    lines = ["; Generated by build.py from model.py. Do not edit.", "",
             "; SQ_LO: floor(n*n/4), n = -256..255, low bytes"]
    lines += data_lines([v & 0xFF for v in squares])
    lines += ["", "; SQ_HI: the high bytes"]
    lines += data_lines([v >> 8 for v in squares])
    lines += ["", f"; SINE_LO: round({model.SINE_SCALE} sin(2 pi a / 256)), a = 0..255, low bytes"]
    lines += data_lines([v & 0xFF for v in sines])
    lines += ["", "; SINE_HI: the high bytes"]
    lines += data_lines([v >> 8 for v in sines])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_rows(path: Path) -> None:
    rows = [model.screen_address(0, y) for y in range(192)]
    lines = ["; Generated by build.py from model.py. Do not edit.", "",
             "; The low bytes of rows 0..191's addresses, then the high"]
    lines += data_lines([r & 0xFF for r in rows])
    lines += ["\t\t\t\t\tDS\t\t64"]
    lines += data_lines([r >> 8 for r in rows])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def objects() -> dict:
    """The demo's objects: {name: (vertices, edges)}, a radius of about 85."""
    cube = [(x, y, z) for x in (-49, 49) for y in (-49, 49) for z in (-49, 49)]
    a, b = 45, round(45 * (1 + 5 ** 0.5) / 2)
    icosahedron = []
    for p, q in ((a, b), (a, -b), (-a, b), (-a, -b)):
        icosahedron += [(0, p, q), (p, q, 0), (q, 0, p)]
    result = {}
    for name, vertices in (("cube", cube), ("icosahedron", icosahedron)):
        lengths = {i: {j: sum((u - v) ** 2 for u, v in zip(vertices[i], vertices[j]))
                       for j in range(len(vertices)) if j != i} for i in range(len(vertices))}
        shortest = min(min(d.values()) for d in lengths.values())
        edges = [(i, j) for i in range(len(vertices)) for j in range(i + 1, len(vertices))
                 if lengths[i][j] <= shortest * 1.01]
        result[name] = (vertices, edges)
    return result


def models() -> dict:
    """The models: {name: (vertices, faces)}. Faces are loops of indices into
    the shared vertices, each wound anticlockwise seen from outside, and
    found from the shape itself: the convex hull's faces, made of the
    vertices on each plane that has them all on one side."""
    import itertools
    result = {}
    shapes = {name: vertices for name, (vertices, _) in objects().items()}
    for name, vertices in shapes.items():
        faces, seen = [], set()
        for a, b, c in itertools.combinations(range(len(vertices)), 3):
            pa, pb, pc = vertices[a], vertices[b], vertices[c]
            u = [pb[i] - pa[i] for i in range(3)]
            v = [pc[i] - pa[i] for i in range(3)]
            n = (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
            if n == (0, 0, 0):
                continue
            side = [sum(n[i] * (q[i] - pa[i]) for i in range(3)) for q in vertices]
            if max(side) > 0 and min(side) < 0:
                continue
            on = tuple(sorted(i for i, s in enumerate(side) if s == 0))
            if on in seen:
                continue
            seen.add(on)
            if max(side) > 0:
                n = tuple(-x for x in n)                  # outwards
            centre = [sum(vertices[i][k] for i in on) / len(on) for k in range(3)]
            # round the face's centre, anticlockwise seen from outside (along -n)
            ref = [vertices[on[0]][k] - centre[k] for k in range(3)]
            other = (n[1] * ref[2] - n[2] * ref[1], n[2] * ref[0] - n[0] * ref[2], n[0] * ref[1] - n[1] * ref[0])
            import math
            def angle(i):
                d = [vertices[i][k] - centre[k] for k in range(3)]
                return math.atan2(sum(d[k] * other[k] for k in range(3)), sum(d[k] * ref[k] for k in range(3)))
            faces.append(sorted(on, key=angle))
        result[name] = (vertices, faces)
    return result


def write_objects(path: Path) -> None:
    lines = ["; Generated by build.py. Do not edit.", ""]
    for name, (vertices, edges) in objects().items():
        lines += [f"{name.upper()}_VERTICES\tEQU\t\t{len(vertices)}",
                  f"{name.upper()}_EDGES\t\tEQU\t\t{len(edges)}", f"{name}_vertices:"]
        lines += [f"\t\t\t\t\tDB\t\t{x}, {y}, {z}" for x, y, z in vertices]
        lines += [f"{name}_edges:"]
        lines += [f"\t\t\t\t\tDB\t\t{i}, {j}" for i, j in edges]
        lines += [""]
    lines += ["; The models, as engine/objects.s reads them: vertices, edges and faces",
              "; (the vertices shared, each edge once), and the bounding radius as",
              "; 128 r and 128 r sqrt 5.", ""]
    for name, (vertices, faces) in models().items():
        edges = model.faces_to_edges(faces)
        r = model.bounding_radius(vertices)
        r_view, r5 = model.cull_radii(r)
        lines += [f"{name}_model:\t\tDB\t\t{len(vertices)}", f"\t\t\t\t\tDW\t\t{name}_vertices",
                  f"\t\t\t\t\tDB\t\t{len(edges)}", f"\t\t\t\t\tDW\t\t{name}_model_edges",
                  f"\t\t\t\t\tDB\t\t{len(faces)}", f"\t\t\t\t\tDW\t\t{name}_faces",
                  f"\t\t\t\t\tDW\t\t{r_view}, {r5}\t\t; r = {r}",
                  f"{name}_model_edges:"]
        lines += [f"\t\t\t\t\tDB\t\t{a}, {b}" for a, b in edges]
        lines += [f"{name}_faces:"]
        lines += [f"\t\t\t\t\tDB\t\t{len(f)}, " + ", ".join(str(i) for i in f) for f in faces]
        lines += [""]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def assemble(name: str) -> None:
    subprocess.run([find_sjasmplus(), f"--sld=output/{name}.sld", "--fullpath",
                    f"--lst=output/{name}.lst", f"{name}.s"], cwd=HERE, check=True)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    write_tables(OUT / "tables_gen.s")
    write_rows(OUT / "rows_gen.s")
    write_objects(OUT / "objects_gen.s")
    assemble("checks")
    print(f"Wrote {OUT / 'checks.bin'}")
    if (HERE / "demo.s").is_file():
        assemble("demo")
        start = find_label(OUT / "demo.sld", "start")
        banks = (OUT / "demo.banks").read_bytes()
        (OUT / "demo.z80").write_bytes(z80file.snapshot_128k(banks, start, 0x07))
        print(f"Wrote {OUT / 'demo.z80'} (128K, PC {start:04X}) and {OUT / 'demo.sld'}")


if __name__ == "__main__":
    main()
