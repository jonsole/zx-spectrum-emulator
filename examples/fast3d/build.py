"""Builds fast3d: the tables, from model.py, into output/tables_gen.s; then
sjasmplus on demo.s, for output/demo.z80 (with its SLD), and on checks.s, the
routines alone at $8000, for output/checks.bin and .sld, which check.py runs.

    python build.py
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "output"
REPO = HERE.parent.parent
sys.path.insert(0, str(HERE))
import model                                                      # noqa: E402

SJASMPLUS = [REPO / "tools" / "sjasmplus" / "sjasmplus.exe",
             REPO / ".venv-win" / "Scripts" / "sjasmplus.exe"]


def find_sjasmplus() -> str:
    for candidate in SJASMPLUS:
        if candidate.is_file():
            return str(candidate)
    found = shutil.which("sjasmplus")
    if found:
        return found
    sys.exit("sjasmplus not found -- see examples/filmation/knightlore/build.py")


def find_label(sld: Path, name: str) -> int:
    """A label's address, from the SLD's label records."""
    for line in sld.read_text(encoding="utf-8").splitlines():
        fields = line.split("|")
        if len(fields) >= 8 and fields[6] == "L":
            parts = fields[7].split(",")
            if len(parts) > 2 and parts[1] == name and parts[2] == "":
                return int(fields[5])
    sys.exit(f"no label {name} in {sld}")


def data_lines(values: list[int]) -> list[str]:
    return ["\t\t\t\t\tDB\t\t" + ",".join(f"${v & 0xFF:02X}" for v in values[i:i + 16])
            for i in range(0, len(values), 16)]


def write_tables(path: Path) -> None:
    squares = [model.quarter_square(n) for n in range(-256, 256)]
    sines = [model.sine(a) & 0xFFFF for a in range(256)]
    lines = ["; Generated by build.py from model.py. Do not edit.", "",
             "; SQ_LO: floor(n*n/4), n = -256..255, low bytes"]
    lines += data_lines([v & 0xFF for v in squares])
    lines += ["", "; SQ_HI: the high bytes"]
    lines += data_lines([v >> 8 for v in squares])
    lines += ["", f"; SINE_LO: round({model.SINE_SCALE} sin(2 pi a / 256)), a = 0..255, low bytes"]
    lines += data_lines([v & 0xFF for v in sines])
    lines += ["", "; SINE_HI: the high bytes"]
    lines += data_lines([v >> 8 for v in sines])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def assemble(name: str) -> None:
    subprocess.run([find_sjasmplus(), f"--sld=output/{name}.sld", "--fullpath",
                    f"--lst=output/{name}.lst", f"{name}.s"], cwd=HERE, check=True)


def main() -> None:
    OUT.mkdir(exist_ok=True)
    write_tables(OUT / "tables_gen.s")
    assemble("checks")
    print(f"Wrote {OUT / 'checks.bin'}")
    if (HERE / "demo.s").is_file():
        assemble("demo")
        print(f"Wrote {OUT / 'demo.z80'}")


if __name__ == "__main__":
    main()
