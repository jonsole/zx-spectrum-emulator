def find_sjasmplus() -> str:
    for candidate in SJASMPLUS:
        if candidate.is_file():
            return str(candidate)
    found = shutil.which("sjasmplus")
    if found:
        return found
    sys.exit("sjasmplus not found -- see examples/filmation/knightlore/build.py")


def find_label(sld: Path, name: str) -> int:
    """A label's address, from the SLD's label records."""
    for line in sld.read_text(encoding="utf-8").splitlines():
        fields = line.split("|")
        if len(fields) >= 8 and fields[6] == "L":
            parts = fields[7].split(",")
            if len(parts) > 2 and parts[1] == name and parts[2] == "":
                return int(fields[5])
    sys.exit(f"no label {name} in {sld}")


def data_lines(values: list[int]) -> list[str]:
    return ["\t\t\t\t\tDB\t\t" + ",".join(f"${v & 0xFF:02X}" for v in values[i:i + 16])
            for i in range(0, len(values), 16)]


def write_tables(path: Path) -> None:
    squares = [model.quarter_square(n) for n in range(-256, 256)]
    sines = [model.sine(a) & 0xFFFF for a in range(256)]
    lines = ["; Generated by build.py from model.py. Do not edit.", "",
             "; SQ_LO: floor(n*n/4), n = -256..255, low bytes"]
    lines += data_lines([v & 0xFF for v in squares])
    lines += ["", "; SQ_HI: the high bytes"]
    lines += data_lines([v >> 8 for v in squares])
    lines += ["", f"; SINE_LO: round({model.SINE_SCALE} sin(2 pi a / 256)), a = 0..255, low bytes"]
    lines += data_lines([v & 0xFF for v in sines])
    lines += ["", "; SINE_HI: the high bytes"]
    lines += data_lines([v >> 8 for v in sines])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_rows(path: Path) -> None:
    rows = [model.screen_address(0, y) for y in range(192)]
    lines = ["; Generated by build.py from model.py. Do not edit.", "",
             "; The low bytes of rows 0..191's addresses, then the high"]
    lines += data_lines([r & 0xFF for r in rows])
    lines += ["\t\t\t\t\tDS\t\t64"]
    lines += data_lines([r >> 8 for r in rows])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def paired(vertices: list) -> list:
    """The vertices, those whose mirror -v is there too first, each followed
    by its mirror: transform_object rotates the first of a pair and has the
    second for nothing, as the negative."""
    rest, pairs, singles = list(vertices), [], []
    while rest:
        v = rest.pop(0)
        mirror = tuple(-c for c in v)
        if mirror in rest:
            rest.remove(mirror)
            pairs += [v, mirror]
        else:
            singles.append(v)
    return pairs + singles


def mirror_pairs(vertices: list) -> int:
    """How many pairs paired() put first."""
    n = 0
    while 2 * n + 1 < len(vertices) and vertices[2 * n + 1] == tuple(-c for c in vertices[2 * n]):
        n += 1
    return n


def objects() -> dict:
    """The demo's objects: {name: (vertices, edges)}, a radius of about 85."""
    cube = [(x, y, z) for x in (-49, 49) for y in (-49, 49) for z in (-49, 49)]
    a, b = 45, round(45 * (1 + 5 ** 0.5) / 2)
    icosahedron = []
    for p, q in ((a, b), (a, -b), (-a, b), (-a, -b)):
        icosahedron += [(0, p, q), (p, q, 0), (q, 0, p)]
    result = {}
    for name, vertices in (("cube", cube), ("icosahedron", icosahedron)):
        vertices = paired(vertices)
        lengths = {i: {j: sum((u - v) ** 2 for u, v in zip(vertices[i], vertices[j]))
                       for j in range(len(vertices)) if j != i} for i in range(len(vertices))}
        shortest = min(min(d.values()) for d in lengths.values())
        edges = [(i, j) for i in range(len(vertices)) for j in range(i + 1, len(vertices))
                 if lengths[i][j] <= shortest * 1.01]
        result[name] = (vertices, edges)
    return result


def models() -> dict:
    """The models: {name: (vertices, faces)}. Faces are loops of indices into
    the shared vertices, each wound anticlockwise seen from outside, and
    found from the shape itself: the convex hull's faces, made of the
    vertices on each plane that has them all on one side."""
    return {name: (vertices, hull_faces(vertices)) for name, (vertices, _) in objects().items()}


def check_models() -> dict:
    """Models for the checks alone: {name: (vertices, faces, parts)}, parts
    being how many of the faces each part has, in order ([] for a model with
    no faces, drawn whole). A box as big as signed bytes allow and a flat
    strip like a runway's, facing up, so that the near plane's cut is tried
    at the extremes of a model's camera-space coordinates; an aeroplane of
    three convex parts, body, wings and tail, for back faces part by part;
    and a frame, a cube with no faces."""
    box = [(x, y, z) for x in (-127, 127) for y in (-127, 127) for z in (-127, 127)]
    strip = [(x, 0, z) for x in (-24, 24) for z in (-127, 127)]
    body = [(x, y, z) for x in (-14, 14) for y in (-16, 14) for z in (-70, 50)]
    wings = [(x, y, z) for x in (-120, 120) for y in (16, 22) for z in (-6, 30)]
    # the tail rises from the body's rear top edge, which both parts have
    tail = [(-14, 14, -70), (14, 14, -70), (0, 14, -110), (0, 44, -110), (0, 40, -92)]
    frame = [(x, y, z) for x in (-60, 60) for y in (-60, 60) for z in (-60, 60)]
    result = {name: parts_model(parts) for name, parts in
              (("box", [box]), ("strip", [strip]), ("aeroplane", [body, wings, tail]))}
    vertices, faces, _ = parts_model([frame])
    result["frame"] = (vertices, faces, [])
    return result


def parts_model(parts: list) -> tuple:
    """A model of convex parts, each a list of vertices, which parts that
    meet share: (vertices, faces, parts) as check_models() has them, the
    vertices paired, each part's faces its convex hull's -- or, for a flat
    part, its one face, wound to face up (+y) or else towards +z."""
    vertices = paired(list(dict.fromkeys(v for part in parts for v in part)))
    faces, counts = [], []
    for part in parts:
        part_faces = [[vertices.index(part[i]) for i in face] for face in hull_faces(part)]
        if len(part_faces) == 1:                      # flat: which way it faces is ours to say
            a, b, c = (vertices[i] for i in part_faces[0][:3])
            u, w = [b[k] - a[k] for k in range(3)], [c[k] - a[k] for k in range(3)]
            n = (u[1] * w[2] - u[2] * w[1], u[2] * w[0] - u[0] * w[2], u[0] * w[1] - u[1] * w[0])
            if (n[1], n[2]) < (0, 0):
                part_faces[0].reverse()
        faces += part_faces
        counts.append(len(part_faces))
    return vertices, faces, counts


def hull_faces(vertices: list) -> list:
    """The faces of the vertices' convex hull (models() says how)."""
    import itertools
    faces, seen = [], set()
    for a, b, c in itertools.combinations(range(len(vertices)), 3):
        pa, pb, pc = vertices[a], vertices[b], vertices[c]
        u = [pb[i] - pa[i] for i in range(3)]
        v = [pc[i] - pa[i] for i in range(3)]
        n = (u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0])
        if n == (0, 0, 0):
            continue
        side = [sum(n[i] * (q[i] - pa[i]) for i in range(3)) for q in vertices]
        if max(side) > 0 and min(side) < 0:
            continue
        on = tuple(sorted(i for i, s in enumerate(side) if s == 0))
        if on in seen:
            continue
        seen.add(on)
        if max(side) > 0:
            n = tuple(-x for x in n)                  # outwards
        centre = [sum(vertices[i][k] for i in on) / len(on) for k in range(3)]
        # round the face's centre, anticlockwise seen from outside (along -n)
        ref = [vertices[on[0]][k] - centre[k] for k in range(3)]
        other = (n[1] * ref[2] - n[2] * ref[1], n[2] * ref[0] - n[0] * ref[2], n[0] * ref[1] - n[1] * ref[0])
        import math
        def angle(i):
            d = [vertices[i][k] - centre[k] for k in range(3)]
            return math.atan2(sum(d[k] * other[k] for k in range(3)), sum(d[k] * ref[k] for k in range(3)))
        faces.append(sorted(on, key=angle))
    return faces


def write_objects(path: Path) -> None:
    lines = ["; Generated by build.py. Do not edit.", ""]
    for name, (vertices, edges) in objects().items():
        lines += [f"{name.upper()}_VERTICES\tEQU\t\t{len(vertices)}",
                  f"{name.upper()}_EDGES\t\tEQU\t\t{len(edges)}", f"{name}_vertices:"]
        lines += [f"\t\t\t\t\tDB\t\t{x}, {y}, {z}" for x, y, z in vertices]
        lines += [f"{name}_edges:"]
        lines += [f"\t\t\t\t\tDB\t\t{i}, {j}" for i, j in edges]
        lines += [""]
    lines += ["; The models, as engine/objects.s reads them: vertices and edges (the",
              "; vertices shared, each edge once), and no faces, so drawn whole; the",
              "; bounding radius, 24-bit, as cull_object tests with it: 128 r and",
              "; 128 r sqrt 5 with the rough step's margins, then without; and how many",
              "; of the vertices, from the first, come as a vertex and its mirror.", ""]
    for name, (vertices, faces) in models().items():
        lines += model_block(name, vertices, faces, [])         # no faces: every edge drawn
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def model_block(name: str, vertices: list, faces: list, parts: list) -> list[str]:
    """A model as engine/objects.s reads it, at {name}_model; its vertices,
    at {name}_vertices, are written apart. parts: how many of the faces each
    convex part has (model.part_edges); [] for a model with no faces, drawn
    whole, whose faces only say what its edges are."""
    edges, edge_faces = model.part_edges(faces, parts)
    assert len(edges) <= 255 and (not parts or len(faces) <= 64), "facing_edges' table holds 64 faces"
    r = model.bounding_radius(vertices)
    r_view, r5 = model.cull_radii(r)
    lines = [f"{name}_model:\t\tDB\t\t{len(vertices)}", f"\t\t\t\t\tDW\t\t{name}_vertices",
             f"\t\t\t\t\tDB\t\t{len(edges)}", f"\t\t\t\t\tDW\t\t{name}_model_edges",
             f"\t\t\t\t\tDB\t\t{len(faces) if parts else 0}", f"\t\t\t\t\tDW\t\t{name}_faces" if parts else "\t\t\t\t\tDW\t\t0",
             f"\t\t\t\t\tD24\t\t{r_view} + ROUGH, {r5} + 3 * ROUGH, {r_view}, {r5}\t\t; r = {r}",
             f"\t\t\t\t\tDB\t\t{mirror_pairs(vertices)}\t\t\t\t\t; v, -v pairs",
             f"\t\t\t\t\tDW\t\t{name}_edge_faces" if parts else "\t\t\t\t\tDW\t\t0",
             f"{name}_model_edges:"]
    lines += [f"\t\t\t\t\tDB\t\t{a}, {b}" for a, b in edges]
    if parts:
        lines += [f"{name}_faces:"]
        lines += [f"\t\t\t\t\tDB\t\t{len(f)}, " + ", ".join(str(i) for i in f) for f in faces]
        lines += [f"{name}_edge_faces:"]
        lines += [f"\t\t\t\t\tDB\t\t{f1}, {f2}" for f1, f2 in edge_faces]
    return lines + [""]


def write_check_models(path: Path) -> None:
    """check_models(), for checks.s alone."""
    lines = ["; Generated by build.py. Do not edit.", "; Models for check.py alone.", ""]
    for name, (vertices, faces, parts) in check_models().items():
        lines += [f"{name}_vertices:"] + [f"\t\t\t\t\tDB\t\t{x}, {y}, {z}" for x, y, z in vertices]
        lines += model_block(name, vertices, faces, parts)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


WORLD_OBJECTS = 40


def world() -> list:
    """The demo's world: (position, angles, spin, model name) for each object,
    scattered round the circle the camera flies, but none within 300 units of
    its path, as before edges were cut at the near plane: the flight cuts
    nothing unless it is steered, and its pictures are as they were."""
    import random
    rng = random.Random(1983)
    path, position, angles = [], [0, 0, 0], [0, 0, 0]
    for _ in range(256):
        position, angles, _ = model.fly(position, angles)
        path.append(position)
    centre = [sum(p[i] for p in path) / len(path) for i in range(3)]
    objects_, names = [], list(objects())
    while len(objects_) < WORLD_OBJECTS:
        pos = [round(centre[0]) + rng.randint(-2600, 2600), rng.randint(-500, 500),
               round(centre[2]) + rng.randint(-2600, 2600)]
        if min(sum((a - b) ** 2 for a, b in zip(pos, p)) for p in path) < 300 ** 2:
            continue
        if any(sum((a - b) ** 2 for a, b in zip(pos, o[0])) < 260 ** 2 for o in objects_):
            continue
        spin = [rng.randint(0, 3), rng.randint(1, 3), rng.randint(0, 2)]
        objects_.append((pos, [rng.randrange(256) for _ in range(3)], spin, names[len(objects_) % len(names)]))
    return objects_


def point_pages(counts: list) -> int:
    """How many pages of points the demo needs to hold every object's at once:
    an object goes on the page it fits, else the next, from vertex 0, so a
    page is left only with more than 64 - the most vertices a model has used
    on it."""
    most = max(counts)
    assert most <= 64, "a model's points must fit one page"
    return (sum(counts) - 1) // (65 - most) + 1


def write_world(path: Path) -> None:
    shapes = models()
    counts = [len(shapes[name][0]) for _, _, _, name in world()]
    lines = ["; Generated by build.py. Do not edit.", "",
             f"WORLD_OBJECTS\t\tEQU\t\t{WORLD_OBJECTS}",
             f"POINT_PAGES\t\t\tEQU\t\t{point_pages(counts)}\t\t\t\t; for all {sum(counts)} vertices at once", "",
             "; Each object: x, y, z; three angles; its model; how much it turns a",
             "; frame, about each axis; and room for the cull to skip it (OBJECT_SIZE",
             "; bytes).", "world:"]
    for pos, angles, spin, name in world():
        lines.append(f"\t\t\t\t\tDW\t\t{pos[0]}, {pos[1]}, {pos[2]}")
        lines.append(f"\t\t\t\t\tDB\t\t{angles[0]}, {angles[1]}, {angles[2]}")
        lines.append(f"\t\t\t\t\tDW\t\t{name}_model")
        lines.append(f"\t\t\t\t\tDB\t\t{spin[0]}, {spin[1]}, {spin[2]}")
        lines.append("\t\t\t\t\tDW\t\t0\t\t\t\t\t; OBJECT_SKIP, OBJECT_DIST, OBJECT_LIMIT")
        lines.append("\t\t\t\t\tDB\t\t0")
        lines.append("\t\t\t\t\tDW\t\t0")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")



X_STEP_OUT_OF_LINE = False   # along x: the row step out of line, so that staying on the row falls through


def write_lines(path: Path) -> None:
    """draw_line's blocks (engine/line.s has the setup and the reasoning). Along
    x: eight a direction, one a bit of the byte; a pixel is SET b,(HL), and
    the next bit is the next block, the next byte INC L or DEC L once in
    eight. Along y: sixty-four a direction, one a bit and a row of the
    character cell, so that seven rows in eight step down with INC H alone
    and only the eighth works out the next cell; the blocks are laid out in
    chains that follow a step across (the next bit, the next row), and a
    pixel that stays in its bit jumps to its own bit's next row. Both
    tables of entries sit within a page, so the setup indexes them with a
    byte."""
    out = ["; Generated by build.py. Do not edit: engine/line.s says how it goes.", ""]

    def down_row(label: str) -> list[str]:
        # A kept in C: down a row from HL, into the next character row or third if need be
        return [f"\t\t\t\t\tld\t\tc,a", f"\t\t\t\t\tinc\t\th", f"\t\t\t\t\tld\t\ta,h", f"\t\t\t\t\tand\t\t7",
                f"\t\t\t\t\tjr\t\tnz,{label}.done", f"\t\t\t\t\tld\t\ta,l", f"\t\t\t\t\tadd\t\ta,32",
                f"\t\t\t\t\tld\t\tl,a", f"\t\t\t\t\tjr\t\tc,{label}.done", f"\t\t\t\t\tld\t\ta,h",
                f"\t\t\t\t\tsub\t\t8", f"\t\t\t\t\tld\t\th,a", f"{label}.done:\tld\t\ta,c"]

    def next_cell() -> list[str]:
        # the eighth row: into the next character row or third; A kept in C
        return [f"\t\t\t\t\tld\t\tc,a", f"\t\t\t\t\tld\t\ta,l", f"\t\t\t\t\tadd\t\ta,32", f"\t\t\t\t\tld\t\tl,a",
                f"\t\t\t\t\tjr\t\tc,$ + 6", f"\t\t\t\t\tld\t\ta,h", f"\t\t\t\t\tsub\t\t8", f"\t\t\t\t\tld\t\th,a",
                f"\t\t\t\t\tld\t\ta,c"]

    # along x: A the error, D the length along x, E along y, B the pixels left
    out += ["; Along x, to the right then the left: x_entries by the first pixel's bit.",
            "\t\t\t\t\tALIGN\t32", "x_entries:"]
    for side, bits, step in (("r", range(7, -1, -1), "inc"), ("l", range(8), "dec")):
        out.append("\t\t\t\t\tDW\t\t" + ", ".join(f"{side}x{7 - i}" for i in range(8)))
    stubs = []
    for side, bits, step in (("r", list(range(7, -1, -1)), "inc"), ("l", list(range(8)), "dec")):
        for i, b in enumerate(bits):
            label = f"{side}x{b}"
            after = f"{side}x{bits[i + 1]}" if i < 7 else f"{side}x_byte"
            out += [f"{label}:\t\t\t\tset\t\t{b},(hl)", "\t\t\t\t\tdec\t\tb", "\t\t\t\t\tret\t\tz",
                    "\t\t\t\t\tsub\t\te"]
            if X_STEP_OUT_OF_LINE:
                out.append(f"\t\t\t\t\tjr\t\tc,{label}_step")
                stubs += [f"{label}_step:\t\tadd\t\ta,d"] + down_row(f"{label}_step") + [f"\t\t\t\t\tjp\t\t{after}"]
            else:
                out += [f"\t\t\t\t\tjr\t\tnc,{after}", "\t\t\t\t\tadd\t\ta,d"] + down_row(label)
        out += [f"{side}x_byte:\t\t\t{step}\t\tl", f"\t\t\t\t\tjp\t\t{side}x{bits[0]}"]
    out += stubs

    # along y: A the error, D the length along y, E along x, B the pixels left
    out += ["", "; Along y: y_entries by the first pixel's bit and row, right then left.",
            "\t\t\t\t\tALIGN\t256", "y_entries:"]
    for side in "rl":
        for i in range(8):
            out.append("\t\t\t\t\tDW\t\t" + ", ".join(f"{side}y{7 - i}_{r}" for r in range(8)))
    for side, bits, step in (("r", list(range(7, -1, -1)), "inc"), ("l", list(range(8)), "dec")):
        for d in range(8):
            for i, b in enumerate(bits):
                r = (d + i) % 8
                label = f"{side}y{b}_{r}"
                out += [f"{label}:\t\t\tset\t\t{b},(hl)", "\t\t\t\t\tdec\t\tb", "\t\t\t\t\tret\t\tz",
                        "\t\t\t\t\tinc\t\th"]
                if r == 7:
                    out += next_cell()
                out += ["\t\t\t\t\tsub\t\te", f"\t\t\t\t\tjp\t\tnc,{side}y{b}_{(r + 1) % 8}", "\t\t\t\t\tadd\t\ta,d"]
            out += [f"\t\t\t\t\t{step}\t\tl", f"\t\t\t\t\tjp\t\t{side}y{bits[0]}_{d}"]
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def assemble(name: str, out: str | None = None, **defines: int) -> None:
    """name.s, with its SLD and listing as output/out (name unless said)."""
    out = out or name
    subprocess.run([find_sjasmplus(), f"--sld=output/{out}.sld", "--fullpath",
                    f"--lst=output/{out}.lst"] + [f"-D{k}={v}" for k, v in defines.items()]
                   + [f"{name}.s"], cwd=HERE, check=True)


def main() -> None:
    cull_skip = 0 if "--no-cull-skip" in sys.argv[1:] else 1     # the demo's CULL_SKIP
    OUT.mkdir(exist_ok=True)
    write_tables(OUT / "tables_gen.s")
    write_rows(OUT / "rows_gen.s")
    write_lines(OUT / "lines_gen.s")
    write_objects(OUT / "objects_gen.s")
    write_world(OUT / "world_gen.s")
    write_check_models(OUT / "check_models_gen.s")
    assemble("checks", CULL_SKIP=1)                                # check.py reads what it leaves
    assemble("checks", out="checks_wrap", CULL_SKIP=1, WORLD_WRAP=1)   # and with the world wrapping
    print(f"Wrote {OUT / 'checks.bin'} and {OUT / 'checks_wrap.bin'}")
    if (HERE / "demo.s").is_file():
        assemble("demo", out="demo_wrap", CULL_SKIP=1, WORLD_WRAP=1)  # for check.py, which moves its world
        assemble("demo", CULL_SKIP=cull_skip)
        start = find_label(OUT / "demo.sld", "start")
        banks = (OUT / "demo.banks").read_bytes()
        (OUT / "demo.z80").write_bytes(z80file.snapshot_128k(banks, start, 0x07))
        print(f"Wrote {OUT / 'demo.z80'} (128K, PC {start:04X}) and {OUT / 'demo.sld'}")


if __name__ == "__main__":
    main()
